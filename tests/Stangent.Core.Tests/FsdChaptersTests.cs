using System.Text.Json.Nodes;
using Stangent.Graph;
using Stangent.Spec.Fsd;

namespace Stangent.Core.Tests;

/// <summary>Chapter files and their hidden ids (phase fs layer 1, D377, D378, D382, D384, D391): the writer, the reader,
/// import, <c>fsd migrate</c> and <c>fsd export --whole</c>. No AI.</summary>
public sealed class FsdChaptersTests : IDisposable
{
    readonly TempRepo archive = new();
    readonly TempRepo repo;

    public FsdChaptersTests() : this(1500) { }

    FsdChaptersTests(int maxLines) => repo = new TempRepo(Config(archive.Root, maxLines));

    static string Config(string archive, int maxLines) =>
        $"version: 1\nfsd: {{ archive: {{ name: docs, path: '{archive}', git: false }}, exportMaxLines: {maxLines} }}\n";

    public void Dispose()
    {
        repo.Dispose();
        archive.Dispose();
    }

    string Root => repo.Root;

    static JsonObject S(string id, string kind, string title, int level, string? parent, int line, string pid, string[] lines, int end)
    {
        var text = string.Join('\n', lines[line..end]).Trim('\n');
        var o = new JsonObject
        {
            ["id"] = id, ["idKind"] = kind, ["title"] = title, ["level"] = level, ["line"] = line, ["text"] = text, ["textHash"] = CanonicalJson.Hash(text), ["permanentId"] = pid,
        };
        if (parent is not null) o["parent"] = parent;
        return o;
    }

    /// <summary>Every field document.json holds for a section, as the reader gives it.</summary>
    static void SameSections(IEnumerable<JsonObject> recorded, IReadOnlyList<ChapterSection> read)
    {
        var expected = recorded.Select(s => ((string)s["id"]!, (string)s["idKind"]!, (string)s["title"]!, (int)s["level"]!, (string?)s["parent"], (string)s["text"]!, (string)s["textHash"]!, (int)s["line"]!, (string?)s["permanentId"])).ToList();
        Assert.Equal(expected, read.Select(s => (s.Id, s.IdKind, s.Title, s.Level, s.Parent, s.Text, s.TextHash, s.Line, s.PermanentId)).ToList());
    }

    // ---- the writer and the reader ----

    const string Tricky = """
        Front words.

        # 1 Orders

        # of retries is three.

        \# already escaped

        ```text
        # a comment in a fence
        ```

        ## 2023 Roadmap

        Plans.

        # 2 Billing

        Pay.

        """;

    static (string Md, List<JsonObject> Sections) TrickyDoc()
    {
        var md = Tricky.Replace("\r\n", "\n");
        var lines = md.Split('\n');
        return (md, [
            S("1", "number", "Orders", 1, null, 3, "S-0001", lines, 12),
            S("Orders / 2023 Roadmap", "path", "2023 Roadmap", 2, "1", 13, "S-0002", lines, 16),
            S("2", "number", "Billing", 1, null, 17, "S-0003", lines, lines.Length),
        ]);
    }

    [Fact]
    public void Chapters_read_back_byte_for_byte_with_ids_hidden_on_headings()
    {
        var (md, sections) = TrickyDoc();
        var (files, over) = FsdChapters.Cut(md, sections, 1500);
        Assert.Empty(over);
        Assert.Equal([FsdChapters.FrontMatter, "01-s0001-orders.md", "02-s0003-billing.md"], files.Select(f => f.Name));
        var orders = files[1].Body;
        Assert.StartsWith("# 1 Orders <!-- S-0001 -->\n", orders);
        // A line that would read as a heading gets a backslash, in a code fence too: no converter writes fences, so none are read.
        Assert.Contains("\n\\# of retries is three.\n", orders);
        Assert.Contains("\n\\\\# already escaped\n", orders);
        Assert.Contains("\n\\# a comment in a fence\n", orders);
        // The import read no number on "2023 Roadmap", and the marker says so.
        Assert.Contains("\n## 2023 Roadmap <!-- S-0002 no-number -->\n", orders);

        var read = FsdChapters.Read(files);
        Assert.Equal(md, read.Markdown);
        SameSections(sections, read.Sections);
        Assert.Null(read.Sections[1].Number);
        Assert.Equal("1", read.Sections[0].Number);
        Assert.Equal(("02-s0003-billing.md", 1), (read.Sections[2].File, read.Sections[2].FileLine));
        Assert.Empty(read.Unmarked);
        Assert.Empty(read.Repeated);
    }

    [Fact]
    public void A_stray_fence_and_a_number_the_heading_does_not_show_read_back()
    {
        // A paragraph that opens a code fence and never closes it, and the attached-files section (AttachmentHome): number 2, no number on its heading.
        var md = "# 1 Orders\n\n```not closed\n\n# Files attached to this document\n\nThis section is generated by stangent.\n";
        var lines = md.Split('\n');
        List<JsonObject> sections = [S("1", "number", "Orders", 1, null, 1, "S-0001", lines, 4), S("2", "number", "Files attached to this document", 1, null, 5, "S-0002", lines, lines.Length)];
        var files = FsdChapters.Cut(md, sections, 1500).Files;
        Assert.StartsWith("# Files attached to this document <!-- S-0002 number=2 -->\n", files[1].Body);
        var read = FsdChapters.Read(files);
        Assert.Equal(md, read.Markdown);
        SameSections(sections, read.Sections);
        Assert.Equal("2", read.Sections[1].Number);
    }

    [Fact]
    public void A_line_break_the_disk_would_change_writes_nothing()
    {
        var md = "# 1 Orders\n\nOne line.\r\nAnother.\n";
        var lines = md.Split('\n');
        var docDir = Path.Combine(Root, "specs", "fsd", "x");
        Assert.Equal("chapters_out_of_step", Assert.Throws<StangentException>(() => FsdChapters.Write(docDir, md, [S("1", "number", "Orders", 1, null, 1, "S-0001", lines, lines.Length)], 1500)).Code);
        Assert.False(Directory.Exists(FsdChapters.Dir(docDir)));
    }

    [Fact]
    public void A_record_out_of_step_with_its_text_writes_nothing()
    {
        var (md, sections) = TrickyDoc();
        sections[1]["text"] = "Other plans.";
        var docDir = Path.Combine(Root, "specs", "fsd", "x");
        Assert.Equal("chapters_out_of_step", Assert.Throws<StangentException>(() => FsdChapters.Write(docDir, md, sections, 1500)).Code);
        Assert.False(Directory.Exists(FsdChapters.Dir(docDir)));
    }

    [Fact]
    public void A_heading_typed_with_no_marker_is_read_with_no_id_and_a_repeated_marker_is_listed()
    {
        var (md, sections) = TrickyDoc();
        var files = FsdChapters.Cut(md, sections, 1500).Files;
        files[1] = (files[1].Name, files[1].Body.Replace("# 1 Orders <!-- S-0001 -->", "# 1 Ordering <!-- S-0001 -->") + "\n## 1.1 New rule\n\nA new sentence.\n");
        files[2] = (files[2].Name, files[2].Body.Replace("S-0003", "S-0001"));
        var read = FsdChapters.Read(files);
        // A rename keeps the id: it moves with its heading (D382).
        Assert.Equal(("S-0001", "Ordering", "1"), (read.Sections[0].PermanentId, read.Sections[0].Title, read.Sections[0].Number));
        var added = Assert.Single(read.Unmarked);
        Assert.Equal(("1.1", "New rule", "1", "A new sentence."), (added.Number, added.Title, added.Parent, added.Text));
        Assert.Equal(["S-0001"], read.Repeated);
    }

    [Fact]
    public void Files_are_read_by_the_numbers_their_names_start_with()
    {
        Assert.Equal(["00-front-matter.md", "01-00-s0001-a.md", "01-02-s0003-b.md", "01-11-s0004-c.md", "01-100-s0005-d.md", "02-s0006-e.md", "notes.md"],
            FsdChapters.Order(["notes.md", "02-s0006-e.md", "01-100-s0005-d.md", "01-11-s0004-c.md", "01-02-s0003-b.md", "00-front-matter.md", "01-00-s0001-a.md"]));
    }

    // ---- import ----

    const string Outline = """
        % Shop
        Words before the first heading.

        #! Orders
        The orders screen has a Place order button.
        - Pay by card
        - Pay by invoice

        ## 3.1 Typed
        The number of items is shown.

        | Field | Rule |
        | Qty | 1 to 9 |

        #! Billing
        ## Refunds
        Refunds take five days.
        ## Refunds
        A second section with one title.
        # Glossary
        Terms.
        """;

    JsonObject Document(string doc) => JsonNode.Parse(File.ReadAllText(Path.Combine(FsdImport.DocDir(Root, doc), "document.json")))!.AsObject();

    void ReadsAsRecorded(string doc)
    {
        var dir = FsdImport.DocDir(Root, doc);
        Assert.False(File.Exists(Path.Combine(dir, "document.md")));
        var read = FsdChapters.Read(FsdChapters.Files(dir));
        SameSections(Document(doc)["sections"]!.AsArray().OfType<JsonObject>(), read.Sections);
        Assert.Empty(read.Unmarked);
        Assert.Empty(read.Repeated);
        Assert.Empty(FsdHandEdit.Sections(dir, Document(doc)));
    }

    [Fact]
    public void A_docx_import_writes_chapters_that_read_back_as_document_json()
    {
        var file = Path.Combine(Root, "shop.docx");
        File.WriteAllBytes(file, DocxWriter.Write(Outline));
        var result = FsdImport.Import(repo.Repo, file);
        Assert.Equal("chapters", (string)result["chapters"]!["dir"]!);
        Assert.Contains(FsdChapters.FrontMatter, result["chapters"]!["files"]!.AsArray().Select(f => (string)f!));
        ReadsAsRecorded("shop");
    }

    [Fact]
    public void The_sonarr_fsd_reads_back_as_document_json()
    {
        var root = AppContext.BaseDirectory;
        while (!File.Exists(Path.Combine(root, "benchmark", "fsd", "sonarr", "sonarr-fsd.docx"))) root = Directory.GetParent(root)!.FullName;
        var file = Path.Combine(Root, "sonarr.docx");
        File.Copy(Path.Combine(root, "benchmark", "fsd", "sonarr", "sonarr-fsd.docx"), file);
        FsdImport.Import(repo.Repo, file, "sonarr");
        ReadsAsRecorded("sonarr");
    }

    [Fact]
    public void A_pdf_import_reads_back_as_document_json()
    {
        using var pdf = new PdfFixture();
        pdf.Page("1 Fields", "Words before.");
        pdf.Page("1.1 More", "# of fields is two.");
        var file = Path.Combine(Root, "shop.pdf");
        File.WriteAllBytes(file, pdf.Build(PdfFixture.Mark("1 Fields", 0, 1, PdfFixture.Mark("1.1 More", 1, 2))));
        FsdImport.Import(repo.Repo, file);
        ReadsAsRecorded("shop");
    }

    [Fact]
    public void An_xlsx_import_reads_back_as_document_json()
    {
        var file = Path.Combine(Root, "rates.xlsx");
        File.WriteAllBytes(file, XlsxFixture.Build([
            new("2024 Rates", XlsxFixture.Row(1, XlsxFixture.Str("A1", "Tier"), XlsxFixture.Str("B1", "Fee")) + XlsxFixture.Row(2, XlsxFixture.Str("A2", "# Gold"), XlsxFixture.Num("B2", "12"))),
            new("Notes", XlsxFixture.Row(1, XlsxFixture.Str("A1", "Only"))),
        ]));
        FsdImport.Import(repo.Repo, file);
        ReadsAsRecorded("rates");
    }

    [Fact]
    public void A_long_chapter_is_cut_at_its_sub_headings_and_still_reads_back()
    {
        using var small = new FsdChaptersTests(3);
        var file = Path.Combine(small.Root, "shop.docx");
        File.WriteAllBytes(file, DocxWriter.Write(Outline));
        var names = FsdImport.Import(small.repo.Repo, file)["chapters"]!["files"]!.AsArray().Select(f => (string)f!).ToList();
        Assert.Contains(names, n => n.StartsWith("02-00-", StringComparison.Ordinal));
        Assert.Contains(names, n => n.StartsWith("02-01-", StringComparison.Ordinal));
        Assert.Contains(names, n => n.StartsWith("02-02-", StringComparison.Ordinal));
        small.ReadsAsRecorded("shop");
    }

    // ---- export --whole ----

    [Fact]
    public void Export_whole_writes_the_document_as_one_file_without_markers()
    {
        var file = Path.Combine(Root, "shop.docx");
        File.WriteAllBytes(file, DocxWriter.Write(Outline));
        FsdImport.Import(repo.Repo, file);
        var result = FsdExport.Run(Root, "shop", null, 1500, whole: true);
        Assert.True((bool)result["whole"]!);
        var only = Assert.Single(Directory.GetFiles(FsdExport.DefaultDir(Root, "shop")));
        Assert.Equal("shop.md", Path.GetFileName(only));
        var text = File.ReadAllText(only);
        Assert.DoesNotContain("<!-- S-", text);
        Assert.EndsWith(Chapters.Text(FsdImport.DocDir(Root, "shop")).TrimEnd('\n') + "\n", text);
        // The chapters' own export still works, one file per chapter.
        Assert.True(FsdExport.Run(Root, "shop", null, 1500)["files"]!.AsArray().Count > 1);
    }

    // ---- migrate ----

    void Commit()
    {
        Git.Run(Root, "add -A");
        Assert.NotNull(Git.Run(Root, "-c user.name=test -c user.email=test@example.invalid commit -q -m fixture"));
    }

    /// <summary>A document as an import before phase fs left it: document.md and no chapters, committed.</summary>
    Dictionary<string, byte[]> OldStyle()
    {
        var file = Path.Combine(Root, "shop.docx");
        File.WriteAllBytes(file, DocxWriter.Write(Outline));
        FsdImport.Import(repo.Repo, file);
        var dir = FsdImport.DocDir(Root, "shop");
        var chapters = Chapters.Files(dir);
        File.WriteAllText(Path.Combine(dir, "document.md"), Chapters.Text(dir));
        Directory.Delete(FsdChapters.Dir(dir), recursive: true);
        Assert.NotNull(Git.Run(Root, "init -q"));
        Commit();
        return chapters;
    }

    [Fact]
    public void Migrate_writes_the_chapters_an_import_would_and_removes_document_md()
    {
        var expected = OldStyle();
        var dir = FsdImport.DocDir(Root, "shop");
        var json = File.ReadAllBytes(Path.Combine(dir, "document.json"));
        var result = FsdMigrate.Run(repo.Repo, "shop");
        Assert.Equal("migrated", (string)result["status"]!);
        Assert.Equal(expected, Chapters.Files(dir));
        Assert.False(File.Exists(Path.Combine(dir, "document.md")));
        Assert.Equal(json, File.ReadAllBytes(Path.Combine(dir, "document.json")));
        ReadsAsRecorded("shop");
        Commit();
        Assert.Equal("unchanged", (string)FsdMigrate.Run(repo.Repo, "shop")["status"]!);
    }

    [Fact]
    public void Migrate_is_refused_with_uncommitted_changes_or_a_hand_edit_and_changes_nothing()
    {
        OldStyle();
        var dir = FsdImport.DocDir(Root, "shop");
        var md = Path.Combine(dir, "document.md");
        File.WriteAllText(md, File.ReadAllText(md).Replace("Refunds take five days.", "Refunds take ten days."));
        Assert.Equal("uncommitted_changes", Assert.Throws<StangentException>(() => FsdMigrate.Run(repo.Repo, "shop")).Code);
        Commit();
        Assert.Equal("document_edited", Assert.Throws<StangentException>(() => FsdMigrate.Run(repo.Repo, "shop")).Code);
        Assert.True(File.Exists(md));
        Assert.False(FsdChapters.Has(dir));
    }

    [Fact]
    public void Migrate_needs_a_git_checkout()
    {
        var file = Path.Combine(Root, "shop.docx");
        File.WriteAllBytes(file, DocxWriter.Write(Outline));
        FsdImport.Import(repo.Repo, file);
        var dir = FsdImport.DocDir(Root, "shop");
        File.WriteAllText(Path.Combine(dir, "document.md"), Chapters.Text(dir));
        Directory.Delete(FsdChapters.Dir(dir), recursive: true);
        Assert.Equal("not_git", Assert.Throws<StangentException>(() => FsdMigrate.Run(repo.Repo, "shop")).Code);
    }
}
