using System.Text.Json.Nodes;
using Stangent.Graph;
using Stangent.Spec.Fsd;
using static Stangent.Core.Tests.FsdLinkTests;

namespace Stangent.Core.Tests;

/// <summary>Journeys read from Playwright tests (D129, D149), with the real reader, a fake graph and throwaway specs. The reader's own cases are in tools/ts-extractor/test/testSteps.test.ts.</summary>
public class TestJourneyTests
{
    const string On = "components: { test-journeys: true }\n";
    const string Import = "import { test, expect } from '@playwright/test';\n";

    static CodeGraph Graph(params string[] routes)
    {
        var graph = new CodeGraph { Commit = "0123456789abcdef0123456789abcdef01234567", DirtyFiles = [], NotInCommit = [] };
        graph.LinkedNodes.AddRange(routes.Select(r => new Node($"page:web/tsconfig.json|{r}", NodeKind.Page, r, "project:web/tsconfig.json", "web/src/routes.ts", 3, 3)));
        return graph;
    }

    static void Write(SpecApp app, string rel, string text)
    {
        var path = Path.Combine(app.Root, rel);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, text);
    }

    static void Spec(SpecApp app, string rel, string body) => Write(app, rel, $"{Import}test('walks', async ({{ page }}) => {{\n{body}\n}});\n");

    static JsonObject Run(SpecApp app, CodeGraph? graph = null, string? outDir = null) => TestJourneys.Command(app.Repo.Config, app.Root, () => graph ?? Graph(), outDir);

    static string Read(SpecApp app, string name) => File.ReadAllText(Path.Combine(TestJourneys.DirIn(app.Root), name));

    [Fact]
    public void Plain_steps_are_listed_in_order_with_their_lines_and_words()
    {
        var app = App(On);
        Spec(app, "e2e/a.spec.ts", "  await page.goto('/invoices');\n  await page.getByRole('button', { name: 'New' }).click();\n  await page.getByLabel('Name').fill('Ann');\n  await expect(page.getByText('Saved')).toBeVisible();");
        var result = Run(app, Graph("/invoices"));

        Assert.True((bool)result["written"]!);
        Assert.Equal(1, (int)result["tests"]!);
        Assert.Equal(4, (int)result["steps"]!);
        Assert.Equal(0, (int)result["unknown"]!);
        var text = Read(app, "e2e/a.spec.ts.md");
        Assert.StartsWith("<!-- Generated by stangent workflows tests", text);
        Assert.Contains("## walks", text);
        Assert.Contains("1. **Go to**: `page.goto('/invoices')` (line 3) → screen `/invoices`, no reference page yet", text);
        Assert.Contains("2. **Click**: `page.getByRole('button', { name: 'New' }).click()` (line 4)", text);
        Assert.Contains("3. **Fill in**: `page.getByLabel('Name').fill('Ann')` (line 5)", text);
        Assert.Contains("4. **Check**: `expect(page.getByText('Saved')).toBeVisible()` (line 6)", text);
        Assert.Contains("It judges nothing", text);
    }

    [Fact]
    public void A_helper_is_left_as_unknown_with_why_and_counted_and_nothing_is_invented()
    {
        var app = App(On);
        Spec(app, "e2e/a.spec.ts", "  await emptyCart(page);");
        var result = Run(app);

        Assert.Equal(1, (int)result["steps"]!);
        Assert.Equal(1, (int)result["unknown"]!);
        Assert.Equal(1, (int)result["unknownByReason"]!["a helper function, which isn't followed"]!);
        Assert.Contains("1. ❓ `emptyCart(page)` (line 3): a helper function, which isn't followed", Read(app, "e2e/a.spec.ts.md"));
        Assert.Contains("- 1: a helper function, which isn't followed", Read(app, "index.md"));
    }

    [Fact]
    public void A_computed_selector_is_unknown()
    {
        var app = App(On);
        Spec(app, "e2e/a.spec.ts", "  await page.locator(`.row-${id}`).click();");
        Run(app);
        Assert.Contains("1. ❓ **Click**: `` page.locator(`.row-${id}`).click() `` (line 3): a computed selector", Read(app, "e2e/a.spec.ts.md"));
    }

    [Fact]
    public void A_goto_links_to_a_recorded_reference_page_and_one_with_no_screen_says_so()
    {
        var app = App(On);
        Write(app, "specs/reference/screens/orders.json", """{ "id": "page:/orders", "sections": [] }""");
        Spec(app, "e2e/a.spec.ts", "  await page.goto('/orders');\n  await page.goto('/gone');\n  await page.goto(url);\n  await admin.goto('/orders');");
        var result = Run(app, Graph("/orders"));

        Assert.Equal(4, (int)result["gotos"]!);
        Assert.Equal(1, (int)result["gotosResolved"]!);
        Assert.Equal(1, (int)result["gotosToReferencePage"]!);
        Assert.Equal(3, (int)result["unknown"]!);
        var text = Read(app, "e2e/a.spec.ts.md");
        Assert.Contains("→ [/orders](../../../reference/screens/orders.md)", text);
        Assert.Contains("❓ **Go to**: `page.goto('/gone')` (line 4): no page resolved. playwright goto: no screen on the map has the route /gone", text);
        Assert.Contains("❓ **Go to**: `page.goto(url)` (line 5): no page resolved. playwright goto: a built URL", text);
        Assert.Contains("(line 6): no page resolved. playwright goto: on admin, not a plain page", text);
    }

    [Fact]
    public void A_rebuild_gives_the_same_bytes_and_removes_only_its_own_old_files_in_its_folder()
    {
        var app = App(On);
        Spec(app, "e2e/a.spec.ts", "  await page.goto('/a');");
        Spec(app, "e2e/b.spec.ts", "  await page.goto('/b');");
        Write(app, "specs/workflows/tests/mine.md", "a person's notes\n");
        Write(app, "specs/workflows/other.md", "<!-- Generated by stangent workflows tests\n");
        Run(app);
        var first = Read(app, "e2e/a.spec.ts.md") + Read(app, "index.md");
        Run(app);
        Assert.Equal(first, Read(app, "e2e/a.spec.ts.md") + Read(app, "index.md"));

        File.Delete(Path.Combine(app.Root, "e2e/b.spec.ts"));
        var result = Run(app);
        Assert.Equal(1, (int)result["removed"]!);
        Assert.False(File.Exists(Path.Combine(TestJourneys.DirIn(app.Root), "e2e/b.spec.ts.md")));
        Assert.True(File.Exists(Path.Combine(TestJourneys.DirIn(app.Root), "mine.md")));
        Assert.True(File.Exists(Path.Combine(app.Root, "specs/workflows/other.md")));
    }

    [Fact]
    public void A_moved_step_leaves_the_files_name_alone()
    {
        var app = App(On);
        Spec(app, "e2e/a.spec.ts", "  await page.goto('/a');");
        Run(app);
        Spec(app, "e2e/a.spec.ts", "\n\n  await page.goto('/a');");
        Assert.Equal(0, (int)Run(app)["removed"]!);
    }

    [Fact]
    public void Another_runners_test_beside_a_config_is_left_out()
    {
        var app = App(On);
        Write(app, "web/playwright.config.ts", "export default {};\n");
        Write(app, "web/src/add.test.ts", "test('adds', () => { expect(add(1, 1)).toBe(2); });\n");
        Write(app, "web/e2e/a.test.ts", "import { test } from './fixtures';\ntest('walks', async ({ page }) => { await page.goto('/a'); });\n");
        var result = Run(app);

        Assert.Equal(1, (int)result["testFiles"]!);
        Assert.Equal(1, (int)result["otherRunnersTests"]!);
        Assert.False(File.Exists(Path.Combine(TestJourneys.DirIn(app.Root), "web/src/add.test.ts.md")));
    }

    [Fact]
    public void Hooks_are_their_own_blocks_counted_once_and_not_as_tests()
    {
        var app = App(On);
        Write(app, "e2e/a.spec.ts", $"{Import}test.describe('orders', () => {{\n  test.beforeEach(async ({{ page }}) => {{ await page.goto('/a'); }});\n  test('one', async ({{ page }}) => {{ await page.click('b'); }});\n  test('two', async ({{ page }}) => {{ await page.click('c'); }});\n}});\n");
        var result = Run(app);

        Assert.Equal(2, (int)result["tests"]!);
        Assert.Equal(1, (int)result["hooks"]!);
        Assert.Equal(3, (int)result["steps"]!);
        var text = Read(app, "e2e/a.spec.ts.md");
        Assert.Contains("## Before each test in orders", text);
        Assert.Contains("## orders › one", text);
    }

    [Fact]
    public void Tests_made_in_a_loop_are_counted_as_not_read()
    {
        var app = App(On);
        Write(app, "e2e/a.spec.ts", $"{Import}for (const x of xs) {{ test(x, async () => {{}}); }}\n");
        var result = Run(app);
        Assert.Equal(1, (int)result["unknown"]!);
        Assert.Contains("## ❓ Outside any test", Read(app, "e2e/a.spec.ts.md"));
        Assert.Contains("`e2e/a.spec.ts:2`", Read(app, "index.md"));
    }

    [Fact]
    public void Out_writes_elsewhere()
    {
        var app = App(On);
        Spec(app, "e2e/a.spec.ts", "  await page.goto('/a');");
        var result = Run(app, null, "elsewhere");
        Assert.Equal("elsewhere", (string)result["out"]!);
        Assert.True(File.Exists(Path.Combine(app.Root, "elsewhere", "index.md")));
        Assert.False(Directory.Exists(TestJourneys.DirIn(app.Root)));
    }

    [Fact]
    public void Off_it_says_so_writes_nothing_and_needs_no_graph()
    {
        var app = App("");
        Spec(app, "e2e/a.spec.ts", "  await page.goto('/a');");
        var result = TestJourneys.Command(app.Repo.Config, app.Root, () => throw new InvalidOperationException("no graph should be read"));

        Assert.False((bool)result["written"]!);
        Assert.Contains("test-journeys is off", (string)result["off"]!);
        Assert.False(Directory.Exists(TestJourneys.DirIn(app.Root)));
    }

    [Fact]
    public void Off_by_default_with_no_needs()
    {
        var component = StangentComponents.All.Single(c => c.Name == TestJourneys.Component);
        Assert.False(component.OnByDefault);
        Assert.Empty(component.Needs);
        Assert.Contains("workflows tests", component.Commands);
    }
}
