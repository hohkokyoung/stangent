using System.Text.Json.Nodes;
using Stangent.Graph;
using Stangent.Spec.Fsd;

namespace Stangent.Core.Tests;

/// <summary><c>fsd outline</c>, <c>fsd show</c>, <c>fsd export</c> and choosing a chapter (A.10, A.11, E.3, D122). No AI.</summary>
public sealed class FsdViewTests : IDisposable
{
    const string Doc = "# Fruit\n\nApples are sorted by size.\n\n## Pears\n\nPears wait three days.\n\n## Plums\n\nPlums ship the same day.\n\n# Empty chapter\n\n# Veg\n\nLeeks wait a day.\n";

    readonly TempRepo archive = new();
    readonly TempRepo repo;

    public FsdViewTests() => repo = new TempRepo($"version: 1\nfsd: {{ archive: {{ name: a, path: '{archive.Root}', git: false }} }}\n");

    public void Dispose()
    {
        repo.Dispose();
        archive.Dispose();
    }

    string Root => repo.Root;
    string ExportDir => FsdExport.DefaultDir(Root, "shop");

    void Import(string outline = Doc)
    {
        var file = Path.Combine(Root, "shop.docx");
        File.WriteAllBytes(file, DocxWriter.Write(outline));
        FsdImport.Import(repo.Repo, file);
    }

    static string Code(Action a) => Assert.Throws<StangentException>(a).Code;

    JsonObject Document() => FsdOutline.Load(Root, "shop");

    [Fact]
    public void Outline_gives_level_id_title_size_and_each_chapters_place()
    {
        Import();
        var outline = FsdOutline.Outline(Root, "shop")["outline"]!.AsArray().OfType<JsonObject>().ToList();
        Assert.Equal(["Fruit", "Pears", "Plums", "Empty chapter", "Veg"], outline.Select(s => (string)s["title"]!));
        Assert.Equal((1, "S-0001", 5, 1), ((int)outline[0]["level"]!, (string)outline[0]["id"]!, (int)outline[0]["words"]!, (int)outline[0]["chapter"]!));
        Assert.Equal(2, (int)outline[1]["level"]!);
        Assert.Null(outline[1]["chapter"]);
        Assert.Equal(3, (int)outline[4]["chapter"]!);
        Assert.Contains("  - S-0002", FsdOutline.OutlineText(FsdOutline.Outline(Root, "shop")));
    }

    [Fact]
    public void Show_finds_a_section_by_id_or_number_and_says_when_there_is_none()
    {
        Import();
        var byId = FsdOutline.Show(Root, "shop", "S-0002");
        var path = (string)byId["number"]!;
        Assert.Equal("Pears wait three days.", (string)byId["text"]!);
        Assert.Equal("S-0002", (string)FsdOutline.Show(Root, "shop", path)["id"]!);
        Assert.Contains("Pears wait three days.", FsdOutline.ShowText(byId));
        Assert.Equal("not_found", Code(() => FsdOutline.Show(Root, "shop", "S-9999")));
        Assert.Equal("not_found", Code(() => FsdOutline.Outline(Root, "other")));
    }

    [Fact]
    public void A_chapter_is_a_top_level_heading_and_everything_under_it()
    {
        Import();
        Assert.Equal(["Fruit", "Pears", "Plums"], FsdOutline.Chapter(Document(), "1").Select(s => (string)s["title"]!));
        Assert.Equal(["Veg"], FsdOutline.Chapter(Document(), "3").Select(s => (string)s["title"]!));
        Assert.Equal(["Veg"], FsdOutline.Chapter(Document(), "S-0005").Select(s => (string)s["title"]!));
        Assert.Equal("not_found", Code(() => FsdOutline.Chapter(Document(), "4")));
    }

    [Fact]
    public void A_numbered_document_never_falls_back_on_place()
    {
        Import("# 1 Fruit\n\nApples are sorted by size.\n\n# 3 Veg\n\nLeeks wait a day.\n");
        Assert.Equal(["Veg"], FsdOutline.Chapter(Document(), "3").Select(s => (string)s["title"]!));
        Assert.Equal("not_found", Code(() => FsdOutline.Chapter(Document(), "2")));
    }

    [Fact]
    public void Export_writes_a_file_per_chapter_each_saying_it_is_generated_and_empty_sections_keep_their_heading()
    {
        Import();
        var result = FsdExport.Run(Root, "shop", null, 1500);
        var files = Directory.GetFiles(ExportDir).Select(Path.GetFileName).Order(StringComparer.Ordinal).ToList();
        Assert.Equal(["01-s0001-fruit.md", "02-s0004-empty-chapter.md", "03-s0005-veg.md"], files);
        Assert.Equal(3, result["files"]!.AsArray().Count);
        var hash = (string)Document()["original"]!["hash"]!;
        var fruit = File.ReadAllLines(Path.Combine(ExportDir, files[0]!));
        Assert.Contains("Generated by stangent fsd export", fruit[0]);
        Assert.Contains("Never read back", fruit[0]);
        Assert.Contains(hash, fruit[0]);
        Assert.Contains("Plums ship the same day.", File.ReadAllText(Path.Combine(ExportDir, files[0]!)));
        Assert.Contains("# Empty chapter", File.ReadAllText(Path.Combine(ExportDir, files[1]!)));
    }

    [Fact]
    public void A_long_chapter_is_cut_one_level_down_with_the_text_before_its_first_sub_heading_on_its_own()
    {
        Import();
        var result = FsdExport.Run(Root, "shop", null, 3);
        Assert.Equal(["01-00-s0001-fruit.md", "01-01-s0002-pears.md", "01-02-s0003-plums.md", "02-s0004-empty-chapter.md", "03-s0005-veg.md"],
            Directory.GetFiles(ExportDir).Select(Path.GetFileName).Order(StringComparer.Ordinal));
        var first = File.ReadAllText(Path.Combine(ExportDir, "01-00-s0001-fruit.md"));
        Assert.Contains("Apples are sorted", first);
        Assert.DoesNotContain("Pears", first);
        Assert.Empty(result["overLimit"]!.AsArray());
        Assert.Equal("01-01-s0002-pears.md", (string)FsdExport.Run(Root, "shop", null, 1)["overLimit"]![1]!);
        Assert.Equal("usage", Code(() => FsdExport.Run(Root, "shop", null, 0)));
    }

    [Fact]
    public void Export_is_byte_stable_removes_only_what_it_wrote_and_goes_where_it_is_told()
    {
        Import();
        FsdExport.Run(Root, "shop", null, 3);
        var mine = Path.Combine(ExportDir, "mine.md");
        File.WriteAllText(mine, "a person's notes\n");
        var first = Directory.GetFiles(ExportDir).Order(StringComparer.Ordinal).ToDictionary(f => f, File.ReadAllBytes);
        FsdExport.Run(Root, "shop", null, 3);
        Assert.Equal(first.Keys, Directory.GetFiles(ExportDir).Order(StringComparer.Ordinal));
        Assert.All(first, f => Assert.Equal(f.Value, File.ReadAllBytes(f.Key)));

        FsdExport.Run(Root, "shop", null, 1500);
        Assert.True(File.Exists(mine));
        Assert.False(File.Exists(Path.Combine(ExportDir, "01-01-s0002-pears.md")));

        var elsewhere = Path.Combine(Root, "elsewhere");
        var result = FsdExport.Run(Root, "shop", elsewhere, 1500);
        Assert.True(File.Exists(Path.Combine(elsewhere, "03-s0005-veg.md")));
        Assert.Equal("elsewhere", (string)result["out"]!);
    }

    [Fact]
    public void Text_before_the_first_heading_goes_in_front_matter()
    {
        Import("Words before any heading at all.\n\n# Fruit\n\nApples are sorted by size.\n");
        FsdExport.Run(Root, "shop", null, 1500);
        Assert.Contains("Words before any heading", File.ReadAllText(Path.Combine(ExportDir, "00-front-matter.md")));
    }

    [Fact]
    public void Git_ignores_the_default_folder_and_a_folder_it_doesnt_is_said_plainly()
    {
        Import();
        Assert.NotNull(Git.Run(Root, "init -q"));
        Assert.True((bool)FsdExport.Run(Root, "shop", null, 1500)["ignoredByGit"]!);
        Assert.False((bool)FsdExport.Run(Root, "shop", Path.Combine(Root, "elsewhere"), 1500)["ignoredByGit"]!);
    }

    [Fact]
    public void Nothing_in_src_reads_an_export()
    {
        var src = Path.Combine(RepoRoot.Find(), "src");
        var uses = Directory.EnumerateFiles(src, "*.cs", SearchOption.AllDirectories)
            .Where(f => !f.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}", StringComparison.Ordinal) && !f.Contains($"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
            .Where(f => File.ReadAllText(f) is var t && (t.Contains("\"export\"", StringComparison.Ordinal) || t.Contains("FsdExport", StringComparison.Ordinal) || t.Contains("/export", StringComparison.Ordinal)))
            .Select(Path.GetFileName).Order(StringComparer.Ordinal);
        Assert.Equal(["FsdCommands.cs", "FsdExport.cs", "Program.cs"], uses);
        // Program.cs's is the graph's own export; FsdCommands only runs this one, and it only ever writes there.
        Assert.DoesNotContain("FsdExport", File.ReadAllText(Path.Combine(src, "Stangent.Cli/Program.cs")));
        var export = File.ReadAllText(Path.Combine(src, "Stangent.Spec/Fsd/FsdExport.cs"));
        Assert.DoesNotContain("ReadAllText(Path.Combine(dir", export);
    }
}
