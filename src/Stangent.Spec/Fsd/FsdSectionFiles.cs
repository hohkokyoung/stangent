using System.Text;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

namespace Stangent.Spec.Fsd;

/// <summary>
/// D142 with D150: one readable Markdown file per section under <c>specs/fsd/&lt;doc&gt;/sections/</c>, so a person reviewing a spec change in a PR sees a
/// clean diff. Written by code from <c>document.json</c> at a first import and at promote, with <c>section-approval</c> on; never read back. The same
/// document gives the same bytes, and nothing names the source file's hash, so a section nobody changed keeps its file as it was.
/// A section with no text and no files of its own is skipped: its heading is in each child's file, and a file holding one heading line is noise in a diff.
/// </summary>
public static partial class FsdSectionFiles
{
    const int MaxSlug = 60;

    [GeneratedRegex("[^a-z0-9]+")]
    private static partial Regex NotSlug();

    public static string Dir(string root, string doc) => Path.Combine(FsdImport.DocDir(root, doc), "sections");

    static string Marker(string doc) => $"<!-- Generated by stangent from specs/fsd/{doc}/document.json. Never read back: change the FSD and import it again. -->";

    /// <summary>Writes the files and removes, in that folder only, any the document no longer has. Returns the names written.</summary>
    public static List<string> Write(string root, string doc, JsonObject document)
    {
        var sections = document["sections"]!.AsArray().OfType<JsonObject>().ToList();
        var byId = sections.ToDictionary(s => (string)s["id"]!, StringComparer.Ordinal);
        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var s in sections)
        {
            var text = (string)s["text"]!;
            var attached = (s["attachments"]?.AsArray() ?? []).OfType<JsonObject>().Select(a => (string)a["fileName"]!).ToList();
            if (text.Trim().Length == 0 && attached.Count == 0) continue;
            var slug = NotSlug().Replace(((string)s["title"]!).ToLowerInvariant(), "-").Trim('-');
            if (slug.Length > MaxSlug) slug = slug[..MaxSlug].TrimEnd('-');
            var name = $"{(string)s["permanentId"]!}{(slug.Length > 0 ? "-" + slug : "")}.md";

            var path = new List<string>();
            for (var p = (string?)s["parent"]; p is not null && byId.TryGetValue(p, out var up); p = (string?)up["parent"]) path.Insert(0, Shown(up));
            var sb = new StringBuilder(Marker(doc)).Append("\n\n");
            sb.Append($"# {Shown(s)}\n\n");
            sb.Append($"`{(string)s["permanentId"]!}`{(path.Count > 0 ? $" · under {string.Join(" › ", path)}" : "")}\n");
            if (text.Trim().Length > 0) sb.Append('\n').Append(text.Replace("](images/", "](../images/")).Append('\n');
            if (attached.Count > 0) sb.Append("\nAttached: ").Append(string.Join(", ", attached)).Append('\n');
            files[name] = sb.ToString();
        }

        var dir = Dir(root, doc);
        Directory.CreateDirectory(dir);
        foreach (var old in Directory.EnumerateFiles(dir, "*.md").Where(f => !files.ContainsKey(Path.GetFileName(f)))) File.Delete(old);
        foreach (var (name, body) in files)
        {
            var target = Path.Combine(dir, name);
            if (!File.Exists(target) || File.ReadAllText(target) != body) File.WriteAllText(target, body);
        }
        return [.. files.Keys.Order(StringComparer.Ordinal)];
    }

    static string Shown(JsonObject s) => (string)s["idKind"]! == "number" ? $"{s["id"]} {s["title"]}" : (string)s["title"]!;
}
