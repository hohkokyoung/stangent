/// <summary>
/// Layer 5's command (D341): an agent reads the FSD and the source and lists where they differ (D321–D324), and code checks
/// every finding. <c>fsd review</c> prepares one run's input; the driver runs <see cref="Reviewer"/> read-only in a
/// throwaway worktree; <c>fsd review-check</c> checks its findings (one retry, then failing findings are dropped and listed);
/// <c>fsd review-merge</c> unions the checked runs into <c>specs/fsd/&lt;doc&gt;/review.json</c> (contract <c>fsd-review</c> v1)
/// and <c>review.md</c>. All the logic is here; a driver only runs the agent the step names.
/// </summary>
public static partial class FsdReview
{
    public const string Reviewer = "stangent-fsd-reviewer";
    public const string OutputSchema = "fsd-review-output.v2.json";
    public const string Contract = "fsd-review";
    public const int Version = 2;
    public static readonly string[] States = ["gap", "conflict", "undocumented", "match"];
    /// <summary>The states that quote an FSD statement (D366: a match quotes the sentence the code does as written).</summary>
    public static bool QuotesFsd(string state) => state is "gap" or "conflict" or "match";

    const string InputFile = "input.md";
    /// <summary>The FSD as the reviewer reads it, a file beside the input (D401: D323's measured shape).</summary>
    public const string FsdFile = "fsd.md";
    const string OutputFile = "output.json";
    const string Marker = "<!-- Generated by `stangent fsd review-merge` (D341): never read back. Answers don't go here. -->";

    public static string RunDir(string root, string doc, int run) => Path.Combine(root, ".stangent", "fsd", doc, "review", $"run-{run}");
    public static string ReviewJson(string root, string doc) => Path.Combine(FsdImport.DocDir(root, doc), "review.json");
    public static string ReviewMarkdown(string root, string doc) => Path.Combine(FsdImport.DocDir(root, doc), "review.md");

    static string Rel(string root, string path) => Path.GetRelativePath(root, path).Replace('\\', '/');

    static void CheckRun(StangentRepo repo, int run)
    {
        if (run < 1 || run > repo.Config.Fsd.ReviewRuns)
            throw new StangentException("usage", $"--run takes 1 to {repo.Config.Fsd.ReviewRuns} (fsd.reviewRuns).", ExitCodes.Usage);
    }

    // ---- prepare ----------------------------------------------------------------------------------------------------------

    /// <summary>The agent's prompt (D401): D323's measured prompt with no app named and the scope filled in. The FSD is a file
    /// it reads (<see cref="FsdFile"/>, <see cref="Markdown"/>) and its answer a file it writes; the driver fills in both
    /// paths (<c>{{FSD_FILE}}</c>, <c>{{OUTPUT_FILE}}</c>), since they are outside the repo it searches. The repo is not in
    /// it: the agent searches it itself.</summary>
    public static string Input(IReadOnlyList<string> scope)
    {
        var line = scope.Count == 0 ? "the FSD covers every screen of the app."
            : "the FSD covers the screens whose routes start with these prefixes: " + string.Join(", ", scope.Select(s => $"`{s}`")) + ".";
        return Bundles.Instructions("fsd-reviewer.md").Replace("{{SCOPE}}", line);
    }

    /// <summary>The document's sections, each heading carrying its section id in brackets (D321's shape): <c>## 2.1 Library  [section id: 2.1]</c>.</summary>
    public static string Markdown(JsonObject document)
    {
        var sb = new StringBuilder($"# {(string)document["title"]!}\n\n");
        foreach (var s in Sections(document))
        {
            var shown = (string)s["idKind"]! == "number" ? $"{(string)s["id"]!} {(string)s["title"]!}" : (string)s["title"]!;
            sb.Append(new string('#', Math.Min((int)s["level"]! + 1, 6))).Append(' ').Append(shown).Append($"  [section id: {(string)s["id"]!}]\n\n");
            var text = ((string)s["text"]!).Trim('\n');
            if (text.Length > 0) sb.Append(text).Append("\n\n");
        }
        return sb.ToString();
    }

    static List<JsonObject> Sections(JsonObject document) => [.. document["sections"]!.AsArray().OfType<JsonObject>()];

    /// <summary><c>fsd review &lt;doc&gt; --run N</c>: writes the run's input and names the agent, or says the run is current
    /// (same input, same commit, already checked) unless <paramref name="again"/>.</summary>
    public static RunStep Prepare(StangentRepo repo, string doc, int run, bool again)
    {
        CheckRun(repo, run);
        var document = FsdOutline.Load(repo.Root, doc);
        AiPolicy.EnsureAllowed(repo.Config, "fsd review");
        var input = Input(repo.Config.Fsd.Scope);
        var fsd = Markdown(document);
        var hash = "sha256:" + CanonicalJson.Hash(input + "\n" + fsd);
        var commit = Stangent.Graph.Git.Head(repo.Root);
        var dir = RunDir(repo.Root, doc, run);
        if (!again && PageRun.LoadJson(Path.Combine(dir, "state.json")) is JsonObject old
            && (string?)old["stage"] == "checked" && (string?)old["inputs"] == hash && (string?)old["commit"] == commit)
            return new RunStep("current", "none");
        if (Directory.Exists(dir)) Directory.Delete(dir, recursive: true);
        Directory.CreateDirectory(dir);
        File.WriteAllText(Path.Combine(dir, InputFile), input);
        File.WriteAllText(Path.Combine(dir, FsdFile), fsd);
        var state = new JsonObject
        {
            ["doc"] = doc, ["run"] = run, ["inputs"] = hash, ["commit"] = commit,
            ["fsdVersion"] = (string)document["original"]!["hash"]!, ["retryUsed"] = false, ["usage"] = Usage.None.ToJson(),
        };
        Move(repo.Root, state, "prepared", "prepared");
        SaveState(dir, state);
        return Next(repo.Root, dir, "prepared");
    }

    static RunStep Next(string root, string dir, string status) => new(status, "review", Reviewer,
        $"Input: {Rel(root, Path.Combine(dir, InputFile))}\nFSD: {Rel(root, Path.Combine(dir, FsdFile))}\nWrite your JSON to: {Rel(root, Path.Combine(dir, OutputFile))}",
        Rel(root, Path.Combine(dir, OutputFile)), Schema: OutputSchema);

    /// <summary>The run's stage moves through the state module (D114), its history beside the other FSD runs'.</summary>
    static void Move(string root, JsonObject state, string to, string reason) =>
        StateChanges.Apply(root, state, StateKinds.FsdReviewRun, $"{(string)state["doc"]!}/review/run-{(int)state["run"]!}", to, StateActor.Code("stangent fsd review"), reason);

    static void SaveState(string dir, JsonObject state) => Quotes.WriteAtomic(Path.Combine(dir, "state.json"), CanonicalJson.Serialize(state));

    static JsonObject State(string root, string doc, int run) =>
        PageRun.LoadJson(Path.Combine(RunDir(root, doc, run), "state.json")) as JsonObject
        ?? throw new StangentException("not_prepared", $"No review run {run} for {doc}. Run `stangent fsd review {doc} --run {run}` first.", ExitCodes.Usage);

    /// <summary>The limits the driver runs the reviewer under, as the file finder's (D101): read-only search inside the repo,
    /// never stangent's folder, <c>specs/</c> (earlier reviews, the FSD's record) or <c>stangent.yaml</c>, structured output,
    /// and <c>fsd.reviewBudget</c>. A retry gets what is left of the cap. The driver swaps <c>root</c> for a worktree of HEAD.</summary>
    public static JsonObject DriverLimits(StangentRepo repo, string doc, int run)
    {
        var root = AbsoluteRule(repo.Root);
        var cap = repo.Config.Fsd.ReviewBudget;
        var state = PageRun.LoadJson(Path.Combine(RunDir(repo.Root, doc, run), "state.json")) as JsonObject;
        var spent = state is null ? 0 : Usage.FromJson(state["usage"]).CostUsd;
        return new JsonObject
        {
            ["root"] = root,
            // Write only for its answer: the driver allows writes to one throwaway folder outside the repo (D401).
            ["tools"] = "Read,Grep,Glob,Write",
            ["allowedTools"] = new JsonArray($"Read({root}/**)"),
            ["disallowedTools"] = new JsonArray($"Read({root}/.stangent/**)", $"Read({root}/.git/**)", $"Read({root}/specs/**)", $"Read({root}/stangent.yaml)"),
            ["permissionMode"] = "dontAsk",
            ["maxTurns"] = cap.Turns,
            ["maxBudgetUsd"] = Math.Round(Math.Max(cap.Usd - spent, 0.01), 4),
            // The commit the checks hold the evidence to: the driver's worktree is made at it, so a moved HEAD changes nothing.
            ["commit"] = (string?)state?["commit"],
        };
    }

    /// <summary>A Claude Code permission path that names the folder wherever the shell is (D89): <c>/repo</c> → <c>//repo</c>.</summary>
    static string AbsoluteRule(string path)
    {
        var p = Path.GetFullPath(path).Replace('\\', '/').TrimEnd('/');
        if (p.Length >= 2 && p[1] == ':') p = "/" + char.ToLowerInvariant(p[0]) + p[2..];
        return "/" + p;
    }

    /// <summary><c>fsd review-status &lt;doc&gt;</c>: how many runs merge takes and where each stands. Reads only, so a driver can
    /// ask before its cost guard without clearing anything.</summary>
    public static JsonObject Status(StangentRepo repo, string doc)
    {
        FsdOutline.Load(repo.Root, doc);
        var head = Stangent.Graph.Git.Head(repo.Root);
        return new JsonObject
        {
            ["doc"] = doc, ["runs"] = repo.Config.Fsd.ReviewRuns, ["commit"] = head,
            ["run"] = new JsonArray([.. Enumerable.Range(1, Math.Max(repo.Config.Fsd.ReviewRuns, 0)).Select(r =>
            {
                var st = PageRun.LoadJson(Path.Combine(RunDir(repo.Root, doc, r), "state.json")) as JsonObject;
                return (JsonNode)new JsonObject
                {
                    ["run"] = r, ["stage"] = (string?)st?["stage"] ?? "not prepared", ["commit"] = (string?)st?["commit"],
                    ["stale"] = st is not null && (string?)st["commit"] != head,
                };
            })]),
            ["merged"] = File.Exists(ReviewJson(repo.Root, doc)),
        };
    }

    // ---- check ------------------------------------------------------------------------------------------------------------

    /// <summary><c>fsd review-check &lt;doc&gt; --run N</c>: the schema, then each finding's checks (D341 (2)). Any failure and the
    /// retry unused: one retry with every error. After it, findings that still fail are dropped and listed with their reasons;
    /// the rest are the run's answer, in <c>checked.json</c>.</summary>
    public static RunStep Check(StangentRepo repo, string doc, int run, Usage? usage)
    {
        CheckRun(repo, run);
        var dir = RunDir(repo.Root, doc, run);
        var state = State(repo.Root, doc, run);
        if ((string?)state["stage"] == "checked") return new RunStep("current", "none");
        if ((string?)state["stage"] == "failed")
            return new RunStep("failed", "none", Errors: [.. (state["errors"] as JsonArray ?? []).Select(e => (string)e!), $"Run {run} failed; `stangent fsd review {doc} --run {run}` starts it again."]);
        // A second check while the retry is waiting, with no new answer and no call's usage: not the reviewer's failure.
        if ((string?)state["stage"] == "retry" && usage is null && !File.Exists(Path.Combine(dir, OutputFile)))
            throw new StangentException("no_output", $"Run {run}'s retry has no answer yet ({Rel(repo.Root, Path.Combine(dir, OutputFile))}). Run the reviewer with the retry's prompt, or pass --usage for a call that returned nothing.", ExitCodes.Usage);
        state["usage"] = Usage.FromJson(state["usage"]).Add(usage ?? Usage.None).ToJson();
        var document = FsdOutline.Load(repo.Root, doc);
        if ((string)document["original"]!["hash"]! != (string)state["fsdVersion"]!)
            throw new StangentException("fsd_changed", $"{doc} has a new version since run {run} was prepared. Prepare it again: `stangent fsd review {doc} --run {run} --again`.", ExitCodes.Usage);
        // D401: a run prepared before the FSD became a file beside the prompt has no file for a retry to read.
        if (!File.Exists(Path.Combine(dir, FsdFile)))
            throw new StangentException("prepared_before", $"Run {run} of {doc} was prepared before the review's prompt changed (D401). Prepare it again: `stangent fsd review {doc} --run {run} --again`.", ExitCodes.Usage);

        var file = Path.Combine(dir, OutputFile);
        var errors = new List<string>();
        var output = PageChecks.Parse(File.Exists(file) ? File.ReadAllText(file) : "", errors) as JsonObject;
        if (errors.Count == 0 && output is null) errors.Add("The output isn't a JSON object.");
        if (errors.Count == 0) errors.AddRange(SchemaRegistry.Embedded.ValidateDeep(OutputSchema, output!.ToJsonString()).Select(e => $"Schema: {e}"));
        if (output is null && (!File.Exists(file) || new FileInfo(file).Length == 0))
            errors.Insert(0, "You returned no answer (most likely you ran out of turns or budget). This time, answer with the findings you have backed with code so far.");
        var findings = errors.Count == 0 ? output!["findings"]!.AsArray().OfType<JsonObject>().ToList() : [];
        var checker = new FindingChecker(repo.Root, document, (string)state["commit"]!);
        var perFinding = findings.Select(checker.Problems).ToList();
        // D366, D367: a statement is one kind only. The same section and quote as a match and as a gap or conflict in one
        // run: the difference stands (a sentence holding two rules, one followed and one not, is that difference), and the
        // match goes back for the retry, then is dropped. Dropping both would lose a real conflict.
        for (var i = 0; i < findings.Count; i++)
            for (var j = 0; j < findings.Count; j++)
                if (i != j && (string)findings[i]["state"]! == "match" && TwoKinds(findings[i], findings[j]))
                    perFinding[i].Add($"the same statement is also reported as a {(string)findings[j]["state"]!} (findings[{j}]); a sentence with a difference is reported as that difference only, with no match");
        var all = errors.Concat(perFinding.SelectMany((p, i) => p.Select(e => $"findings[{i}]: {e}"))).ToList();

        if (all.Count > 0 && (bool?)state["retryUsed"] != true)
        {
            state["retryUsed"] = true;
            Move(repo.Root, state, "retry", "the code check failed");
            SaveState(dir, state);
            var sb = new StringBuilder("# The code check failed\n\nSome of your output wasn't accepted. Fix every problem below and write the whole output again, ");
            sb.Append("every finding included (after one more check, findings that still fail are dropped).\n\n");
            foreach (var e in all.Take(60)) sb.Append($"- {e}\n");
            if (all.Count > 60) sb.Append($"- … and {all.Count - 60} more\n");
            File.WriteAllText(Path.Combine(dir, "feedback.md"), sb.ToString());
            var previous = Path.Combine(dir, "previous-" + OutputFile);
            if (File.Exists(file)) File.Move(file, previous, overwrite: true); else File.WriteAllText(previous, "(no output)");
            var next = Next(repo.Root, dir, "retry");
            return next with
            {
                Errors = all,
                Prompt = next.Prompt + $"\nYour previous attempt: {Rel(repo.Root, previous)}\nWhat to fix: {Rel(repo.Root, Path.Combine(dir, "feedback.md"))}",
            };
        }

        // No answer at all after the retry: the run failed. Nothing is recorded, so merge won't count it as a run that found
        // nothing, and the next `fsd review` starts it again.
        if (errors.Count > 0)
        {
            Move(repo.Root, state, "failed", "no answer after the retry");
            state["errors"] = new JsonArray([.. errors.Take(10).Select(e => (JsonNode)e)]);
            SaveState(dir, state);
            return new RunStep("failed", "none", Errors: errors);
        }

        var kept = new JsonArray();
        var dropped = new JsonArray();
        for (var i = 0; i < findings.Count; i++)
        {
            var f = Clean(findings[i]);
            if (perFinding[i].Count == 0) kept.Add(f);
            else dropped.Add(new JsonObject { ["finding"] = f, ["reasons"] = new JsonArray([.. perFinding[i].Select(r => (JsonNode)r)]) });
        }
        var result = new JsonObject
        {
            ["doc"] = doc, ["run"] = run, ["commit"] = (string)state["commit"]!, ["fsdVersion"] = (string)state["fsdVersion"]!,
            ["inputs"] = (string)state["inputs"]!, ["retried"] = (bool?)state["retryUsed"] == true, ["usage"] = state["usage"]!.DeepClone(),
            ["findings"] = kept, ["dropped"] = dropped,
        };
        Quotes.WriteAtomic(Path.Combine(dir, "checked.json"), CanonicalJson.Serialize(result));
        Move(repo.Root, state, "checked", dropped.Count > 0 ? $"recorded, {dropped.Count} dropped" : "recorded");
        SaveState(dir, state);
        return new RunStep("recorded", "none", Errors: dropped.Count > 0 ? [.. dropped.Select(d => $"dropped: {string.Join("; ", d!["reasons"]!.AsArray().Select(r => (string)r!))}")] : null);
    }

    /// <summary>The finding as recorded: the schema's fields only, empty strings as null, evidence trimmed.</summary>
    static JsonObject Clean(JsonObject f) => new()
    {
        ["state"] = (string)f["state"]!,
        ["section"] = Blank((string?)f["section"]),
        ["fsdQuote"] = Blank((string?)f["fsdQuote"]),
        ["screen"] = Blank((string?)f["screen"]),
        ["note"] = (string)f["note"]!,
        ["evidence"] = new JsonArray([.. f["evidence"]!.AsArray().Select(e => (JsonNode)((string)e!).Trim())]),
    };

    static string? Blank(string? s) => string.IsNullOrWhiteSpace(s) ? null : s.Trim();

    [GeneratedRegex(@"^(?<path>.+?):(?<from>\d+)(?:\s*[-–]\s*(?<to>\d+))?$")]
    private static partial Regex PathLine();

    [GeneratedRegex(@"[*`]")]
    private static partial Regex Emphasis();

    [GeneratedRegex(@"(?m)^[ \t]*(?:[-*+]|\d+[.)])[ \t]+")]
    private static partial Regex ListMark();

    /// <summary>Curly quotes, long dashes and no-break spaces as typed (a Word FSD has them; a model often straightens them).</summary>
    static string Fold(string s) => s.Replace('\u2018', '\'').Replace('\u2019', '\'').Replace('\u201B', '\'').Replace('\u201C', '"').Replace('\u201D', '"')
        .Replace('\u201E', '"').Replace('\u2013', '-').Replace('\u2014', '-').Replace('\u00A0', ' ');

    /// <summary>Text as compared: folded, emphasis marks deleted (so "the `Save`, button" reads "the Save, button"), and on
    /// request table bars as spaces (a quote across cells) and list markers gone (a quote across items).</summary>
    static string Prep(string s, bool cells, bool marks)
    {
        s = Fold(s);
        if (marks) s = ListMark().Replace(s, "");
        s = Emphasis().Replace(s, "");
        return cells ? s.Replace('|', ' ') : s;
    }

    /// <summary>D341 (2)'s checks, for one run: the reviewed version's sections and the reviewed commit's files.</summary>
    sealed class FindingChecker
    {
        readonly string root;
        readonly string commit;
        readonly Dictionary<string, string> sectionText = new(StringComparer.Ordinal);
        readonly IReadOnlySet<string>? files;
        readonly Dictionary<string, int?> lineCounts = new(StringComparer.Ordinal);

        public FindingChecker(string root, JsonObject document, string commit)
        {
            this.root = root;
            this.commit = commit;
            foreach (var (id, text) in SectionTexts(document)) sectionText[id] = text;
            files = commit.Length > 0 ? Stangent.Graph.Git.FilesAt(root, commit) : null;
        }

        public List<string> Problems(JsonObject f)
        {
            var problems = new List<string>();
            var state = (string)f["state"]!;
            var section = Blank((string?)f["section"]);
            var quote = Blank((string?)f["fsdQuote"]);
            var screen = Blank((string?)f["screen"]);
            if (!States.Contains(state)) problems.Add($"state \"{state}\" isn't one of {string.Join(", ", States)}");
            if (section is not null && !sectionText.ContainsKey(section))
                problems.Add($"there's no section \"{Short(section)}\" in the FSD; give the id exactly as in its heading's brackets");
            if (section is null && !(state == "undocumented" && screen is not null))
                problems.Add(state == "undocumented" ? "an undocumented finding names a screen or a section, and this names neither" : $"a {state} names its FSD section");
            if (QuotesFsd(state) && quote is null) problems.Add($"a {state} quotes the FSD sentence(s) concerned");
            // D366: a match says where the code does it, so a line, not a folder or a whole file.
            if (state == "match" && !f["evidence"]!.AsArray().Any(e => PathLine().IsMatch(((string)e!).Trim())))
                problems.Add("a match gives the line(s) that do it (path:line), not a path alone");
            if (quote is not null && section is not null && sectionText.TryGetValue(section, out var text) && !Quoted(quote, text))
                problems.Add($"the fsdQuote \"{Short(quote)}\" isn't word for word in section {section} (copy whole sentences, at least 4 words, or a whole line)");
            foreach (var e in f["evidence"]!.AsArray().Select(e => ((string)e!).Trim()))
                if (EvidenceProblem(e) is { } p) problems.Add(p);
            return problems;
        }

        static bool Quoted(string quote, string text) => FsdReview.Quoted(quote, text);

        string? EvidenceProblem(string e)
        {
            var m = PathLine().Match(e);
            var path = Clean(m.Success ? m.Groups["path"].Value : e);
            if (path is null) return $"evidence \"{Short(e)}\" isn't a path relative to the repo root";
            if (!m.Success)
                // A path with no line (a gap points at where a thing would be): the file or folder must exist.
                return Exists(path) ? null : $"evidence \"{Short(e)}\": no such file or folder at the reviewed commit";
            if (Lines(path) is not { } count) return $"evidence \"{Short(e)}\": no such file {path} at the reviewed commit";
            var from = int.Parse(m.Groups["from"].Value);
            var to = m.Groups["to"].Success ? int.Parse(m.Groups["to"].Value) : from;
            if (from < 1 || to < from) return $"evidence \"{Short(e)}\": the lines aren't a range";
            return to > count ? $"evidence \"{Short(e)}\": line {to} is past the end of {path} ({count} lines)" : null;
        }

        static string? Clean(string path)
        {
            var p = path.Trim().Replace('\\', '/');
            while (p.StartsWith("./", StringComparison.Ordinal)) p = p[2..];
            return p.Length == 0 || Path.IsPathRooted(p) || p.Split('/').Contains("..") ? null : p.TrimEnd('/');
        }

        bool Exists(string path) => files is not null
            ? files.Contains(path) || files.Any(f => f.StartsWith(path + "/", StringComparison.Ordinal))
            : File.Exists(Path.Combine(root, path)) || Directory.Exists(Path.Combine(root, path));

        int? Lines(string path)
        {
            if (lineCounts.TryGetValue(path, out var hit)) return hit;
            string? text = null;
            if (files is not null) { if (files.Contains(path)) text = Stangent.Graph.Git.Run(root, $"show \"{commit}:./{path}\""); }
            else if (File.Exists(Path.Combine(root, path))) text = File.ReadAllText(Path.Combine(root, path));
            int? count = text is null ? null : text.Length == 0 ? 0 : text.Split('\n').Length - (text.EndsWith('\n') ? 1 : 0);
            lineCounts[path] = count;
            return count;
        }
    }

    /// <summary>Each section's text as quotes are checked against it: its own and its subsections' (check_output.py's rule),
    /// since a quote may sit under a sub-heading. By the section's id (number or heading path).</summary>
    public static Dictionary<string, string> SectionTexts(JsonObject document)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        var sections = Sections(document);
        for (var i = 0; i < sections.Count; i++)
        {
            var level = (int)sections[i]["level"]!;
            var parts = new List<string> { (string)sections[i]["text"]! };
            for (var j = i + 1; j < sections.Count && (int)sections[j]["level"]! > level; j++) parts.Add((string)sections[j]["text"]!);
            result[(string)sections[i]["id"]!] = string.Join("\n\n", parts);
        }
        return result;
    }

    /// <summary>A quote as findings are joined by it (the merge's rule): folded, emphasis gone, spaces collapsed.</summary>
    public static string NormalizeQuote(string? quote) => Norm(quote);

    /// <summary>Word for word (D53's rule: 4 words or a whole line), from a word's start to a word's end; spaces, emphasis,
    /// curly quotes and long dashes ignored, and table bars and list markers too where that is what makes it match.</summary>
    public static bool Quoted(string quote, string text)
    {
        foreach (var cells in new[] { false, true })
            foreach (var marks in new[] { false, true })
            {
                var (q, t) = (Prep(quote, cells, marks), Prep(text, cells, marks));
                if (Quotes.InText(q, t) && WholeWords(Quotes.Normalize(q), Quotes.Normalize(t))) return true;
            }
        return false;
    }

    /// <summary>The quote sits in the text with no letter or digit run on at either end: "he reader shows" isn't from "The reader shows".</summary>
    static bool WholeWords(string q, string t)
    {
        if (q.Length == 0) return false;
        for (var at = t.IndexOf(q, StringComparison.Ordinal); at >= 0; at = t.IndexOf(q, at + 1, StringComparison.Ordinal))
        {
            var end = at + q.Length;
            var startOk = at == 0 || !char.IsLetterOrDigit(t[at - 1]) || !char.IsLetterOrDigit(q[0]);
            var endOk = end == t.Length || !char.IsLetterOrDigit(t[end]) || !char.IsLetterOrDigit(q[^1]);
            if (startOk && endOk) return true;
        }
        return false;
    }

    static string Short(string s) => s.Length > 80 ? s[..80] + "…" : s;

    // ---- merge ------------------------------------------------------------------------------------------------------------

    /// <summary><c>fsd review-merge &lt;doc&gt;</c>: the checked runs 1..fsd.reviewRuns unioned, exact duplicates joined, each
    /// finding saying which runs found it. Every run must be checked, on the same commit and FSD version.</summary>
    public static JsonObject Merge(StangentRepo repo, string doc)
    {
        var document = FsdOutline.Load(repo.Root, doc);
        var runs = new List<JsonObject>();
        for (var run = 1; run <= repo.Config.Fsd.ReviewRuns; run++)
        {
            var path = Path.Combine(RunDir(repo.Root, doc, run), "checked.json");
            runs.Add(PageRun.LoadJson(path) as JsonObject
                ?? throw new StangentException("not_checked", $"Review run {run} of {doc} isn't checked yet. Run `stangent fsd review {doc} --run {run}`, the reviewer, then `stangent fsd review-check {doc} --run {run}`.", ExitCodes.Usage));
        }
        if (runs.Select(r => (string)r["commit"]!).Distinct().Count() > 1 || runs.Select(r => (string)r["fsdVersion"]!).Distinct().Count() > 1)
            throw new StangentException("runs_differ", $"The review runs of {doc} were made on different commits or FSD versions; prepare the older ones again with --again.", ExitCodes.Usage,
                [.. runs.Select(r => $"run {(int)r["run"]!}: commit {(string)r["commit"]!}, FSD {(string)r["fsdVersion"]!}")]);
        if ((string)runs[0]["fsdVersion"]! != (string)document["original"]!["hash"]!)
            throw new StangentException("fsd_changed", $"{doc} has a new version since the runs were made; run the review again.", ExitCodes.Usage);

        var order = Sections(document).Select((s, i) => ((string)s["id"]!, i)).ToDictionary(x => x.Item1, x => x.i, StringComparer.Ordinal);
        var merged = new List<(JsonObject Finding, SortedSet<int> Runs, int Order)>();
        var n = 0;
        foreach (var run in runs)
        {
            var number = (int)run["run"]!;
            var mine = run["findings"]!.AsArray().OfType<JsonObject>().ToList();
            // Only what no earlier run has joined yet: a run says one finding per difference, so a joined finding takes
            // at most one from each run.
            var open = merged.Count;
            foreach (var f in mine)
            {
                n++;
                bool Free(int k) => !merged[k].Runs.Contains(number);
                var same = Enumerable.Range(0, open).Where(k => Free(k) && Same(merged[k].Finding, f,
                    () => mine.Count(g => Compatible(merged[k].Finding, g)) == 1 && Enumerable.Range(0, open).Count(j => Free(j) && Compatible(merged[j].Finding, f)) == 1))
                    .DefaultIfEmpty(-1).First();
                if (same >= 0)
                {
                    merged[same].Runs.Add(number);
                    // The joined finding keeps the first run's words and every run's evidence.
                    var evidence = merged[same].Finding["evidence"]!.AsArray();
                    foreach (var e in f["evidence"]!.AsArray().Select(e => (string)e!).Where(e => evidence.All(x => (string)x! != e))) evidence.Add((JsonNode)e);
                }
                else merged.Add(((JsonObject)f.DeepClone(), [number], n));
            }
        }
        var sorted = merged
            .OrderBy(m => (string?)m.Finding["section"] is { } s && order.TryGetValue(s, out var i) ? i : int.MaxValue)
            .ThenBy(m => Array.IndexOf(States, (string)m.Finding["state"]!)).ThenBy(m => m.Order).ToList();
        var permanent = Sections(document).ToDictionary(s => (string)s["id"]!, s => (string?)s["permanentId"], StringComparer.Ordinal);
        var findings = new JsonArray();
        for (var i = 0; i < sorted.Count; i++)
        {
            var f = sorted[i].Finding;
            var o = new JsonObject { ["id"] = $"F-{i + 1:D3}" };
            foreach (var (k, v) in f) o[k] = v?.DeepClone();
            o["sectionId"] = (string?)f["section"] is { } s ? permanent.GetValueOrDefault(s) : null;
            o["runs"] = new JsonArray([.. sorted[i].Runs.Select(r => (JsonNode)r)]);
            var maybe = sorted.Select((m, j) => (m, j)).Where(x => x.j != i && MaybeSame(f, sorted[i].Runs, x.m.Finding, x.m.Runs)).Select(x => (JsonNode)$"F-{x.j + 1:D3}").ToList();
            if (maybe.Count > 0) o["maybeSameAs"] = new JsonArray([.. maybe]);
            // D366: another run called the same statement a match where this one found a difference (or the other way).
            var disagrees = sorted.Select((m, j) => (m, j)).Where(x => x.j != i && TwoKinds(f, x.m.Finding)).Select(x => (JsonNode)$"F-{x.j + 1:D3}").ToList();
            if (disagrees.Count > 0) o["disagreesWith"] = new JsonArray([.. disagrees]);
            findings.Add(o);
        }
        var usages = runs.Select(r => Usage.FromJson(r["usage"])).ToList();
        var total = usages.Aggregate(Usage.None, (a, b) => a.Add(b));
        var review = new JsonObject
        {
            ["contract"] = Contract, ["version"] = Version, ["doc"] = doc,
            ["commit"] = (string)runs[0]["commit"]!, ["fsdVersion"] = (string)runs[0]["fsdVersion"]!,
            ["model"] = total.Run?.Model ?? total.Model ?? "unknown", ["effort"] = total.Run?.Effort ?? "unknown",
            ["tokens"] = total.InputTokens + total.OutputTokens + total.CacheReadTokens + total.CacheWriteTokens,
            ["costUsd"] = total.CostUsd,
            ["runs"] = new JsonArray([.. runs.Select((r, i) => (JsonNode)new JsonObject
            {
                ["run"] = (int)r["run"]!, ["findings"] = r["findings"]!.AsArray().Count, ["dropped"] = r["dropped"]!.AsArray().Count,
                ["retried"] = (bool)r["retried"]!, ["usage"] = r["usage"]!.DeepClone(),
            })]),
            ["counts"] = new JsonObject([.. States.Select(s => KeyValuePair.Create(s, (JsonNode?)sorted.Count(m => (string)m.Finding["state"]! == s)))]),
            ["findings"] = findings,
            ["dropped"] = new JsonArray([.. runs.SelectMany(r => r["dropped"]!.AsArray().OfType<JsonObject>().Select(d =>
            {
                var o = (JsonObject)d.DeepClone();
                o["run"] = (int)r["run"]!;
                return (JsonNode)o;
            }))]),
        };
        var errors = SchemaRegistry.Embedded.Validate($"fsd-review.v{Version}.json", review.ToJsonString());
        if (errors.Count > 0) throw new StangentException("bad_review", $"review.json doesn't match its contract: {errors[0]}");
        Quotes.WriteAtomic(ReviewJson(repo.Root, doc), CanonicalJson.Serialize(review));
        Quotes.WriteAtomic(ReviewMarkdown(repo.Root, doc), MarkdownReport(document, review));
        return new JsonObject
        {
            ["doc"] = doc, ["file"] = Rel(repo.Root, ReviewJson(repo.Root, doc)), ["markdown"] = Rel(repo.Root, ReviewMarkdown(repo.Root, doc)),
            ["findings"] = findings.Count, ["counts"] = review["counts"]!.DeepClone(), ["dropped"] = review["dropped"]!.AsArray().Count,
            ["foundByEveryRun"] = sorted.Count(m => m.Runs.Count == runs.Count),
            ["maybeSame"] = findings.Count(f => f!["maybeSameAs"] is not null), ["tokens"] = review["tokens"]!.DeepClone(),
        };
    }

    /// <summary>What code can show is one difference (D341 (3), narrowed after Kavita's saved runs): a gap or conflict with
    /// the same section and quote (20 of 20 joins right there); an undocumented screen no section fits, by its route; and
    /// an undocumented finding in a section only when the pairing is unambiguous (<paramref name="unique"/>): compatible,
    /// and each the other's only compatible finding. "An evidence file in common" alone joined different options (a layout
    /// choice with other reader settings, two preference switches crossed), and no two runs cited the same line, so an
    /// ambiguous pair stays apart, marked <see cref="MaybeSame"/>: a near-duplicate costs a reader a glance, a wrong join loses a finding.</summary>
    static bool Same(JsonObject a, JsonObject b, Func<bool> unique)
    {
        var state = (string)a["state"]!;
        if (state != (string)b["state"]!) return false;
        if (state != "undocumented")
            return (string?)a["section"] == (string?)b["section"] && Norm((string?)a["fsdQuote"]) == Norm((string?)b["fsdQuote"]);
        if (!Compatible(a, b)) return false;
        return a["section"] is null || unique();
    }

    /// <summary>Two undocumented findings that may be one: the same section; with none, the same route; with one, routes equal
    /// or one left blank (runs differ on whether an option names its screen), and an evidence file in common.</summary>
    static bool Compatible(JsonObject a, JsonObject b)
    {
        if ((string)a["state"]! != "undocumented" || (string)b["state"]! != "undocumented" || (string?)a["section"] != (string?)b["section"]) return false;
        var (x, y) = ((string?)a["screen"], (string?)b["screen"]);
        bool SameRoute() => x is not null && y is not null && string.Equals(x.TrimEnd('/'), y.TrimEnd('/'), StringComparison.OrdinalIgnoreCase);
        if (a["section"] is null) return SameRoute();
        return (x is null || y is null || SameRoute()) && Files(a).Overlaps(Files(b));
    }

    /// <summary>Undocumented findings of different runs in the same section with an evidence file in common, left apart:
    /// possibly one difference, for the reader to judge.</summary>
    static bool MaybeSame(JsonObject a, IReadOnlySet<int> aRuns, JsonObject b, IReadOnlySet<int> bRuns) =>
        (string)a["state"]! == "undocumented" && (string)b["state"]! == "undocumented"
        && (string?)a["section"] is { } section && section == (string?)b["section"]
        && !aRuns.Overlaps(bRuns) && Files(a).Overlaps(Files(b));

    /// <summary>One section and quote reported as a match and as a gap or conflict (D366).</summary>
    static bool TwoKinds(JsonObject a, JsonObject b)
    {
        var (x, y) = ((string)a["state"]!, (string)b["state"]!);
        return x != y && (x == "match" || y == "match") && QuotesFsd(x) && QuotesFsd(y)
            && (string?)a["section"] is { } section && section == (string?)b["section"] && Norm((string?)a["fsdQuote"]) == Norm((string?)b["fsdQuote"]);
    }

    static string Norm(string? s) => Quotes.Normalize(Prep(s ?? "", cells: false, marks: false));

    static HashSet<string> Files(JsonObject f) => [.. f["evidence"]!.AsArray().Select(e => (string)e!).Select(e => PathLine().Match(e) is { Success: true } m ? m.Groups["path"].Value : e)];

    /// <summary>review.md: the header (commit, FSD version, model, effort, runs, tokens), then each section's gaps, conflicts and
    /// what it leaves out, and last the screens no section covers and what was dropped.</summary>
    static string MarkdownReport(JsonObject document, JsonObject review)
    {
        var sb = new StringBuilder(Marker).Append("\n\n");
        sb.Append($"# FSD review: {(string)document["title"]!} (`{(string)review["doc"]!}`)\n\n");
        var runs = review["runs"]!.AsArray().OfType<JsonObject>().ToList();
        sb.Append($"- Commit `{(string)review["commit"]!}`, FSD version `{(string)review["fsdVersion"]!}`\n");
        sb.Append($"- Model {(string)review["model"]!}, effort {(string)review["effort"]!}; {runs.Count} runs, {(long)review["tokens"]!:N0} tokens\n");
        var counts = review["counts"]!;
        sb.Append($"- {review["findings"]!.AsArray().Count} findings: {(int)counts["gap"]!} gaps, {(int)counts["conflict"]!} conflicts, {(int)counts["undocumented"]!} left out, {(int)counts["match"]!} matches; ");
        sb.Append($"{review["dropped"]!.AsArray().Count} dropped by the code checks\n\n");
        sb.Append("Each finding rests on an AI's reading of the code. Code checked that every FSD quote is word for word in its section and every `file:line` exists; it did not check that the difference is real, or that a matched line does what its sentence says.\n\n");
        var findings = review["findings"]!.AsArray().OfType<JsonObject>().ToList();
        var heads = new (string State, string Title)[] { ("gap", "Gaps (the FSD says it, the code doesn't do it)"), ("conflict", "Conflicts (the code does it differently)"), ("undocumented", "Left out (the code has it, the FSD doesn't say)"), ("match", "Matches (the code does what the FSD says)") };
        void Write(IEnumerable<JsonObject> list)
        {
            foreach (var (state, title) in heads)
            {
                var some = list.Where(f => (string)f["state"]! == state).ToList();
                if (some.Count == 0) continue;
                sb.Append($"### {title}\n\n");
                foreach (var f in some)
                {
                    var found = f["runs"]!.AsArray().Count == runs.Count ? "every run" : "run " + string.Join(", ", f["runs"]!.AsArray().Select(r => (int)r!));
                    sb.Append($"- **{(string)f["id"]!}** {(string)f["note"]!}");
                    if ((string?)f["screen"] is { } screen) sb.Append($" Screen `{screen}`.");
                    sb.Append($" _(found by {found})_");
                    if (f["maybeSameAs"] is JsonArray maybe) sb.Append($" Maybe the same as {string.Join(", ", maybe.Select(m => $"**{(string)m!}**"))}.");
                    if (f["disagreesWith"] is JsonArray other) sb.Append($" The runs disagree: see {string.Join(", ", other.Select(m => $"**{(string)m!}**"))}.");
                    sb.Append('\n');
                    if ((string?)f["fsdQuote"] is { } quote) sb.Append($"  - FSD: “{Quotes.Normalize(quote)}”\n");
                    sb.Append($"  - Code: {string.Join(", ", f["evidence"]!.AsArray().Select(e => $"`{(string)e!}`"))}\n");
                }
                sb.Append('\n');
            }
        }
        foreach (var s in Sections(document))
        {
            var mine = findings.Where(f => (string?)f["section"] == (string)s["id"]!).ToList();
            if (mine.Count == 0) continue;
            var shown = (string)s["idKind"]! == "number" ? $"{(string)s["id"]!} {(string)s["title"]!}" : (string)s["title"]!;
            sb.Append($"## {shown}\n\n");
            Write(mine);
        }
        var loose = findings.Where(f => f["section"] is null).ToList();
        if (loose.Count > 0)
        {
            sb.Append("## Screens no section covers\n\n");
            Write(loose);
        }
        var dropped = review["dropped"]!.AsArray().OfType<JsonObject>().ToList();
        if (dropped.Count > 0)
        {
            sb.Append("## Dropped by the code checks\n\nNot findings: listed so nothing goes missing silently.\n\n");
            foreach (var d in dropped)
                sb.Append($"- run {(int)d["run"]!}, {(string)d["finding"]!["state"]!}: {(string)d["finding"]!["note"]!} — {string.Join("; ", d["reasons"]!.AsArray().Select(r => (string)r!))}\n");
            sb.Append('\n');
        }
        return sb.ToString().TrimEnd('\n') + "\n";
    }
