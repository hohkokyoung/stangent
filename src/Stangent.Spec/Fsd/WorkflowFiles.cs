using System.Text;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using Stangent.Core;
using Stangent.Spec.Pages;
using Stangent.Spec.Trace;

namespace Stangent.Spec.Fsd;

/// <summary>
/// <c>stangent workflows</c> (D144, D147): one readable file per flow and a count per use case, written by code from <c>claims.json</c>, <c>specs/trace.yaml</c> and the pages. They hold no fact of their
/// own: nothing reads them back, a test holds that, and they're in no input hash. The same inputs give the same bytes. A flow's status is by code, with no AI and no tuned number (<c>docs/spec.md</c>).
/// </summary>
public static partial class WorkflowFiles
{
    public const string Component = "workflow-files";
    const string Marker = "<!-- Generated by stangent workflows";
    const int MaxSlug = 60;

    /// <summary>What a flow can be, and what a step can be besides <see cref="Agree"/> and <see cref="Closed"/>.</summary>
    public const string Matches = "matches", Open = "open", Differs = "differs", NotJudged = "not judged", NotAnswered = "not answered";
    const string Agree = "agree", Closed = "closed", Question = "question", Gone = "gone";

    [GeneratedRegex("[^a-z0-9]+")]
    private static partial Regex NotSlug();

    [GeneratedRegex(@"^(\d+)[.)]\s")]
    private static partial Regex StepNumber();

    sealed record Flow(string Id, string? Label, string Name, List<StoredClaim> Steps);

    /// <summary>On only with what it needs (D121): ids to point at come from <c>claim-links</c>, which itself needs <c>fsd-claims</c>.</summary>
    public static bool On(StangentConfig config) => StangentComponents.IsOn(config, Component) && ClaimFile.On(config);

    public static string DirIn(string root, string doc) => Path.Combine(root, "specs", "workflows", doc);

    public static JsonObject Off(StangentConfig config) => new()
    {
        ["written"] = false,
        ["off"] = StangentComponents.IsOn(config, Component)
            ? $"{StangentComponents.MissingNeed(config, Component) ?? StangentComponents.MissingNeed(config, ClaimFile.Component)} Nothing was written."
            : $"{Component} is off (components.{Component}), so nothing was written.",
    };

    /// <summary>What the command does: says so and writes nothing when it's off.</summary>
    public static JsonObject Command(StangentConfig config, string root, string doc) => On(config) ? Run(root, doc) : Off(config);

    public static JsonObject Run(string root, string doc)
    {
        var document = FsdOutline.Load(root, doc);
        // A name like ../fsd/shop reaches a real document and would aim the folder somewhere else.
        if ((string?)document["id"] != doc) throw new StangentException("not_found", $"No imported document {doc}.", ExitCodes.NotFound);
        var claims = ClaimFile.Load(root, doc).All;
        var sections = document["sections"]!.AsArray().OfType<JsonObject>().ToList();
        InStep(doc, sections, claims);

        var byClaim = new Dictionary<string, List<JsonObject>>(StringComparer.Ordinal);
        var bySection = new Dictionary<string, List<JsonObject>>(StringComparer.Ordinal);
        foreach (var e in TraceFile.Sorted(TraceFile.Load(root)["entries"]!.AsArray()).Where(e => (string?)e["fsd"]?["doc"] == doc))
        {
            if ((string?)e["fsd"]?["claim"] is { } claim) (byClaim.TryGetValue(claim, out var on) ? on : byClaim[claim] = []).Add(e);
            if ((string?)e["fsd"]?["sectionId"] is { } section) (bySection.TryGetValue(section, out var of) ? of : bySection[section] = []).Add(e);
        }
        var index = SpecIndex.Load(root);
        var header = $"{Marker} from specs/fsd/{doc}/claims.json, specs/trace.yaml and the reference pages. Never read back, and an edit here is lost: run stangent workflows {doc} again. -->\n\n";

        var claimsOf = claims.ToLookup(c => c.Section, StringComparer.Ordinal);
        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        var lines = new List<string>();
        var totals = Enumerable.ToDictionary([Matches, Open, Differs, NotJudged, NotAnswered], s => s, _ => 0, StringComparer.Ordinal);
        int useCases = 0, flowCount = 0, openQuestions = 0, offFlow = 0, emptyLabels = 0, notOnAStep = 0;
        foreach (var s in sections.Where(s => (string?)s["permanentId"] is not null && claimsOf.Contains((string)s["permanentId"]!)))
        {
            var id = (string)s["permanentId"]!;
            var own = claimsOf[id].OrderBy(c => c.Position).ToList();
            var flows = Flows(own, out var empty);
            if (flows.Count == 0) continue;
            emptyLabels += empty;
            useCases++;
            offFlow += own.Count(c => c.Judged && c.Flow is null);

            var links = bySection.GetValueOrDefault(id) ?? [];
            var judged = links.Any(e => e["fsd"]?["claim"] is not null);
            var placed = flows.SelectMany(f => f.Steps).Select(c => c.Id).ToHashSet(StringComparer.Ordinal);
            var unplaced = links.Count(e => (string?)e["fsd"]?["claim"] is not { } c || !placed.Contains(c));
            notOnAStep += unplaced;

            var folder = Name(id, (string)s["title"]!, "section");
            var counts = new Dictionary<string, int>(StringComparer.Ordinal);
            foreach (var flow in flows)
            {
                var steps = InOrder(flow.Steps).Select(c => (Claim: c, Links: byClaim.GetValueOrDefault(c.Id) ?? [])).ToList();
                var states = steps.Select(x => StepState(x.Links, judged)).ToList();
                var status = StatusOf(states, judged);
                var waiting = steps.Sum(x => x.Links.Count(Waiting));
                counts[status] = counts.GetValueOrDefault(status) + 1;
                totals[status]++;
                openQuestions += waiting;
                flowCount++;
                files[$"{folder}/{Name(flow.Id, flow.Name, "flow")}.md"] = header + Render(flow, s, status, waiting, steps, states, judged ? 0 : unplaced, index);
            }
            var match = counts.GetValueOrDefault(Matches);
            var rest = counts.Where(c => c.Key != Matches).OrderBy(c => c.Key, StringComparer.Ordinal).Select(c => $"{c.Value} {c.Key}");
            lines.Add($"- [{Normalize(s["title"])}]({folder}/): {match} of {flows.Count} {(flows.Count == 1 ? "flow matches" : "flows match")}{string.Concat(rest.Select(r => $", {r}"))}. Section {(string)s["id"]!}.{(unplaced > 0 ? $" {unplaced} {Plural(unplaced, "link")} on no flow's step." : "")}");
        }

        var without = sections.Count - useCases;
        var head = new StringBuilder($"# Workflows: {Normalize(document["title"])}\n\n");
        head.Append($"{flowCount} {Plural(flowCount, "flow")} in {useCases} {Plural(useCases, "use case")}: ")
            .Append(string.Join(", ", totals.Where(t => t.Value > 0).OrderBy(t => t.Key, StringComparer.Ordinal).Select(t => $"{t.Value} {t.Key}").DefaultIfEmpty("nothing to count")))
            .Append($". {openQuestions} open {Plural(openQuestions, "question")}.\n\n");
        head.Append($"{without} of {sections.Count} sections had no flows, so they have no file here.");
        if (offFlow > 0) head.Append($" {offFlow} {Plural(offFlow, "claim")} in these use cases {(offFlow == 1 ? "is" : "are")} in no flow, so {(offFlow == 1 ? "it's" : "they're")} not listed.");
        if (emptyLabels > 0) head.Append($" {emptyLabels} flow {Plural(emptyLabels, "label")} in these use cases had no steps.");
        head.Append('\n');
        if (lines.Count > 0) head.Append('\n').AppendJoin('\n', lines).Append('\n');
        files["index.md"] = header + head;

        var dir = DirIn(root, doc);
        var removed = Sweep(dir, files.Keys);
        foreach (var (name, text) in files)
        {
            var path = Path.Combine(dir, name);
            if (!File.Exists(path) || File.ReadAllText(path) != text) Quotes.WriteAtomic(path, text);
        }
        return new JsonObject
        {
            ["written"] = true, ["doc"] = doc, ["out"] = Path.GetRelativePath(root, dir), ["files"] = files.Count, ["removed"] = removed,
            ["useCases"] = useCases, ["flows"] = flowCount, ["sections"] = sections.Count, ["sectionsWithNoFlows"] = without, ["openQuestions"] = openQuestions,
            ["statuses"] = new JsonObject(totals.OrderBy(t => t.Key, StringComparer.Ordinal).Select(t => KeyValuePair.Create(t.Key, (JsonNode?)t.Value))),
            ["claimsInNoFlow"] = offFlow, ["labelsWithNoSteps"] = emptyLabels, ["linksOnNoStep"] = notOnAStep,
        };
    }

    /// <summary>A file of old claims would show a document that's gone, so it's refused. This writes nothing outside its folder, so it doesn't catch them up itself.</summary>
    static void InStep(string doc, List<JsonObject> sections, IReadOnlyList<StoredClaim> claims)
    {
        var filed = claims.ToLookup(c => c.Section, StringComparer.Ordinal);
        var withText = sections.Where(s => ((string)s["text"]!).Trim().Length > 0).ToList();
        var ids = withText.Select(s => (string?)s["permanentId"]).ToHashSet(StringComparer.Ordinal);
        var same = filed.All(f => ids.Contains(f.Key)) && withText.All(s =>
            filed[(string?)s["permanentId"] ?? ""].OrderBy(c => c.Position).Select(c => c.Normalized).SequenceEqual(FsdClaims.Split((string)s["text"]!).Select(c => Quotes.Normalize(c.Words)), StringComparer.Ordinal));
        if (!same) throw new StangentException("claims_out_of_step", $"specs/fsd/{doc}/claims.json isn't this document's claims. Run `stangent fsd claims {doc}`, then this again.");
    }

    /// <summary>
    /// A section's flows, in order, from where the claims sit. A flow label starts a new flow, so two with the same words stay two. A flow with no label of its own is named by its first step. A label
    /// with nothing under it is counted and has no flow, and steps that carry on with no new label stay in their flow.
    /// </summary>
    static List<Flow> Flows(List<StoredClaim> own, out int emptyLabels)
    {
        var flows = new List<Flow>();
        var current = new Dictionary<string, Flow>(StringComparer.Ordinal);
        string? label = null;
        emptyLabels = 0;
        foreach (var c in own)
        {
            if (c.Kind == FsdClaims.Kinds.FlowLabel)
            {
                if (label is not null) emptyLabels++;
                label = c.Id;
            }
            else if (c.Flow is null)
            {
                if (label is not null) emptyLabels++;
                label = null;
            }
            else if (c.Judged)
            {
                if (label is not null || !current.TryGetValue(c.Flow, out var flow))
                {
                    flow = new Flow(label ?? c.Id, label, c.Flow, []);
                    flows.Add(flow);
                    current[c.Flow] = flow;
                    label = null;
                }
                flow.Steps.Add(c);
            }
        }
        if (label is not null) emptyLabels++;
        return flows;
    }

    /// <summary>By each step's own number where every step has one and none repeats, since a table's columns put 5 after 8 when it's read row by row. Otherwise as they sit in the document.</summary>
    static IEnumerable<StoredClaim> InOrder(List<StoredClaim> steps)
    {
        var numbers = steps.Select(c => StepNumber().Match(c.Normalized)).Select(m => m.Success && int.TryParse(m.Groups[1].Value, out var n) ? n : -1).ToList();
        return numbers.All(n => n >= 0) && numbers.Distinct().Count() == numbers.Count ? steps.Zip(numbers).OrderBy(x => x.Second).Select(x => x.First) : steps;
    }

    /// <summary>
    /// What one link says. A person's ruling comes first. <c>accepted</c> is a difference known and left, so it still differs; <c>page-wrong</c> and <c>defer</c> are waiting on someone. A verdict nobody
    /// has confirmed closes nothing (D119), through <see cref="TraceFindings.GoesTo"/>. An <c>unclear</c> finding is a question, not a difference (C.4). A finding a new build no longer finds says nothing.
    /// </summary>
    static string Reading(JsonObject e)
    {
        if (TraceFindings.IsGone(e)) return Gone;
        var finding = TraceFindings.IsFinding(e);
        switch ((string?)e["decision"])
        {
            case "code-wrong" or "fsd-wrong" or "accepted": return Differs;
            case "page-wrong" or "defer": return Open;
            case "agree" or "not-a-difference": return finding ? Closed : Agree;
        }
        if (!finding) return (string?)e["check"] == "disputed" ? Open : Agree;
        if (TraceFindings.GoesTo(e) == "closed") return Closed;
        if ((string?)e["state"] == "conflict" && (string?)e["verdict"] == "stands") return Differs;
        return (string?)e["state"] == "unclear" ? Question : Open;
    }

    static bool Waiting(JsonObject e) => Reading(e) is var r && (r is Open or Question || r == Differs && e["decision"] is null);

    /// <summary>The worst of its links. A question beside an agree or a closed finding leaves the step as it is, and is counted; on its own, it's what's open.</summary>
    static string StepState(List<JsonObject> links, bool judged)
    {
        var readings = links.Select(Reading).ToHashSet(StringComparer.Ordinal);
        if (readings.Contains(Differs)) return Differs;
        if (readings.Contains(Open)) return Open;
        if (readings.Contains(Agree)) return Agree;
        if (readings.Contains(Closed)) return Closed;
        if (readings.Contains(Question)) return Open;
        return judged ? NotAnswered : NotJudged;
    }

    static string StatusOf(List<string> steps, bool judged) =>
        !judged ? NotJudged : steps.Contains(Differs) ? Differs : steps.Contains(Open) ? Open : steps.Contains(NotAnswered) ? NotAnswered : Matches;

    static string Render(Flow flow, JsonObject section, string status, int waiting, List<(StoredClaim Claim, List<JsonObject> Links)> steps, List<string> states, int oldLinks, SpecIndex index)
    {
        var sb = new StringBuilder($"# {Quotes.Normalize(flow.Name)} · {status.ToUpperInvariant()}{(waiting > 0 ? $", {waiting} open {Plural(waiting, "question")}" : "")}\n\n");
        sb.Append($"Section {(string)section["id"]!} {Normalize(section["title"])} (`{(string)section["permanentId"]!}`){(flow.Label is null ? "" : $", flow label `{flow.Label}`")}.\n");
        if (oldLinks > 0) sb.Append($"\n{oldLinks} older {Plural(oldLinks, "link")} on this section {(oldLinks == 1 ? "names" : "name")} no claim, so {(oldLinks == 1 ? "it isn't" : "they aren't")} on a step here.\n");
        for (var i = 0; i < steps.Count; i++)
        {
            var (claim, links) = steps[i];
            sb.Append($"\n**{claim.Normalized}** `{claim.Id}` · {states[i]}{(claim.Problem is null ? "" : $" · cut: {claim.Problem}")}\n");
            foreach (var e in links) sb.Append($"- {Line(e, index)}\n");
        }
        return sb.ToString();
    }

    /// <summary>A link: its state and page statement, with the statement's words filled in from the page's JSON, and what a finding has been through.</summary>
    static string Line(JsonObject e, SpecIndex index)
    {
        var sb = new StringBuilder($"`{(string?)e["state"]}` ↔ ");
        var page = (string?)e["page"]?["id"];
        var statement = (string?)e["page"]?["statement"];
        if (page is null) sb.Append("no page");
        else
        {
            sb.Append($"`{page}`");
            if (statement is not null) sb.Append($" {statement}: {(index.Statement(page, statement) is { } found ? $"\"{Normalize(found["text"])}\"" : "(no such statement on the page now)")}");
        }
        if (TraceFindings.IsFinding(e))
        {
            sb.Append($" · `{(string?)e["finding"] ?? (string?)e["id"]}` · {Verdict(e)} · {Decision(e)}");
            sb.Append(TraceFindings.GoesTo(e) is var goes && goes == "decided" ? "" : $" · {(goes is "closed" or "gone" ? goes : $"with {goes}")}");
        }
        else
        {
            if (e["decision"] is not null) sb.Append($" · {Decision(e)}");
            if ((string?)e["check"] is not "confirmed") sb.Append($" · {((string?)e["check"] == "disputed" ? "disputed by the second check" : "not confirmed by a second check")}");
        }
        return sb.ToString();
    }

    static string Verdict(JsonObject e)
    {
        if ((string?)e["verdict"] is not { } verdict) return "no verdict";
        return (TraceFindings.ReviewHolds(e) ? (string?)e["review"] : null) switch
        {
            "confirmed" => $"verdict {verdict}, confirmed by {(string?)e["review_note"]?["by"]}",
            "sent-back" => $"verdict {verdict}, sent back",
            _ => verdict is "refuted" or "unreachable" ? $"verdict {verdict}, not confirmed" : $"verdict {verdict}",
        };
    }

    static string Decision(JsonObject e) => (string?)e["decision"] is { } decision
        ? $"decision {decision}{((string?)e["decided_by"] is { } by ? $" by {by}" : "")}" : "no decision";

    /// <summary>Removes what an earlier run left that doesn't apply now: only files that say they're ours, only in this folder, and then folders left empty. Returns how many files went.</summary>
    static int Sweep(string dir, IEnumerable<string> keep)
    {
        if (!Directory.Exists(dir)) return 0;
        var wanted = keep.Select(k => Path.GetFullPath(Path.Combine(dir, k))).ToHashSet(StringComparer.Ordinal);
        var removed = 0;
        foreach (var old in Directory.EnumerateFiles(dir, "*.md", SearchOption.AllDirectories).Where(f => !wanted.Contains(Path.GetFullPath(f))).ToList())
        {
            using (var r = new StreamReader(old)) { if (r.ReadLine()?.StartsWith(Marker, StringComparison.Ordinal) != true) continue; }
            File.Delete(old);
            removed++;
        }
        foreach (var folder in Directory.EnumerateDirectories(dir, "*", SearchOption.AllDirectories).OrderByDescending(d => d.Length))
            if (!Directory.EnumerateFileSystemEntries(folder).Any()) Directory.Delete(folder);
        return removed;
    }

    /// <summary><c>s-0120-login</c>, <c>c-2474-first-time-login</c>: a permanent id, so a section's new number renames nothing and two with the same words can't collide, then a slug to read.</summary>
    static string Name(string id, string words, string fallback)
    {
        var slug = NotSlug().Replace(words.ToLowerInvariant(), "-").Trim('-');
        if (slug.Length > MaxSlug) slug = slug[..MaxSlug].TrimEnd('-');
        return $"{id.ToLowerInvariant()}-{(slug.Length == 0 ? fallback : slug)}";
    }

    static string Normalize(JsonNode? text) => Quotes.Normalize((string?)text ?? "");

    static string Plural(int n, string word) => n == 1 ? word : word + "s";
}
