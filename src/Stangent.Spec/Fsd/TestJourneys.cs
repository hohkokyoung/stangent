using System.Text;
using System.Text.Json.Nodes;
using Stangent.Core;
using Stangent.Graph;
using Stangent.Graph.Detectors;
using Stangent.Graph.Loading;
using Stangent.Spec.Pages;
using Stangent.Spec.Trace;

namespace Stangent.Spec.Fsd;

/// <summary>
/// <c>stangent workflows tests</c> (D129, D149): what each Playwright test walks through, in order, read by code with no AI. A goto links to its screen's reference page through the graph's own route
/// resolution; what can't be followed is ❓ with why, and no step is invented. It compares nothing: no FSD, no verdict, no pass count. Nothing reads these files back, and the same inputs give the same bytes.
/// </summary>
public static class TestJourneys
{
    public const string Component = "test-journeys";
    const string Marker = "<!-- Generated by stangent workflows tests";
    const string Header = $"{Marker} from the repo's Playwright tests and the code graph. Never read back, and an edit here is lost: run stangent workflows tests again. -->\n\n";
    const string Unknown = "❓";
    const string GotoNotResolved = "a goto with no screen resolved";
    const string Says = "What the tests walk through, read by code. It judges nothing: no comparison with the FSD, and no pass count.";

    public static bool On(StangentConfig config) => StangentComponents.IsOn(config, Component);

    public static string DirIn(string root) => Path.Combine(root, "specs", "workflows", "tests");

    public static JsonObject Off() => new() { ["written"] = false, ["off"] = $"{Component} is off (components.{Component}), so nothing was written." };

    /// <summary>What the command does: says so and writes nothing when it's off, without needing a graph.</summary>
    public static JsonObject Command(StangentConfig config, string root, Func<CodeGraph> graph, string? outDir = null)
    {
        if (!On(config)) return Off();
        var blind = new List<(string Place, string Why)>();
        var specs = PlaywrightDetector.SpecFiles(root, (place, why) => blind.Add((place, why))).ToList();
        var (lines, error) = FrontendScanner.TestSteps(root, specs.Select(s => s.Spec));
        if (error is not null) throw new StangentException("test_steps_failed", error);
        return Run(root, graph(), lines, specs.Where(s => s.Imports).Select(s => s.Spec).ToHashSet(StringComparer.Ordinal), blind, outDir);
    }

    /// <param name="lines">The reader's output, one JSON line per spec.</param>
    /// <param name="imports">The specs that import Playwright. Any other, beside a config, counts only if the reader saw a step on a page or a browser asked for: it may be another runner's unit test.</param>
    internal static JsonObject Run(string root, CodeGraph graph, IEnumerable<string> lines, IReadOnlySet<string> imports, IReadOnlyList<(string Place, string Why)> blind, string? outDir)
    {
        var pages = PlaywrightDetector.PagesOf(graph);
        var frontends = PlaywrightDetector.FrontendsOf(graph, pages);
        var sameRoute = pages.GroupBy(p => p.Name).ToDictionary(g => g.Key, g => g.Count(), StringComparer.Ordinal);
        var index = SpecIndex.Load(root);
        var dir = outDir is null ? DirIn(root) : Path.GetFullPath(outDir, root);

        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        var totals = new Totals();
        var rows = new List<string>();
        var unread = new List<string>();
        var notBrowser = 0;
        foreach (var o in lines.Select(l => JsonNode.Parse(l)!.AsObject()).OrderBy(o => (string)o["file"]!, StringComparer.Ordinal))
        {
            var spec = (string)o["file"]!;
            if (!imports.Contains(spec) && !(bool)o["browserTest"]!)
            {
                notBrowser++;
                continue;
            }
            var own = new Totals();
            var sb = new StringBuilder();
            foreach (var block in o["blocks"]!.AsArray().OfType<JsonObject>())
                RenderBlock(sb, block, spec, own, Path.Combine(dir, spec + ".md"), pages, frontends, sameRoute, index);
            var notRead = o["unread"]!.AsArray().OfType<JsonObject>().ToList();
            if (notRead.Count > 0)
            {
                sb.Append($"\n## {Unknown} Outside any test\n\n");
                foreach (var u in notRead)
                {
                    sb.Append($"- {Unknown} {Code((string)u["words"]!)} (line {(int)u["line"]!}): {(string)u["reason"]!}\n");
                    own.Count((string)u["reason"]!);
                    unread.Add($"`{spec}:{(int)u["line"]!}`: {(string)u["reason"]!}");
                }
            }
            files[spec + ".md"] = $"{Header}# {spec}\n\n{own.Line()}\n\n{Says}\n{sb}";
            totals.Add(own);
            rows.Add($"- [{spec}]({spec}.md): {own.Line()}");
        }
        foreach (var (place, why) in blind)
        {
            totals.Count(why);
            unread.Add($"`{place}`: {why}");
        }
        unread = [.. unread.Order(StringComparer.Ordinal)];

        var head = new StringBuilder($"{Header}# What the tests walk through\n\n{Says}\n\n{rows.Count} test {Plural(rows.Count, "file")}: {totals.Line()}\n\n");
        head.Append($"{totals.GotosResolved} of {totals.Gotos} gotos reach a screen, and {totals.ToReference} of those a reference page. Only a goto says which page it's on: a click can go anywhere, so the steps after one aren't placed on a page.\n");
        if (totals.ByKind.Count > 0) head.Append($"\nSteps by kind: {string.Join(", ", totals.ByKind.OrderBy(k => k.Key, StringComparer.Ordinal).Select(k => $"{k.Value} {k.Key}"))}.\n");
        if (totals.ByReason.Count > 0)
        {
            head.Append($"\n## {Unknown} by reason\n\n");
            foreach (var (why, n) in totals.ByReason.OrderByDescending(r => r.Value).ThenBy(r => r.Key, StringComparer.Ordinal)) head.Append($"- {n}: {why}\n");
        }
        if (rows.Count > 0) head.Append("\n## Test files\n\n").AppendJoin('\n', rows).Append('\n');
        if (unread.Count > 0) head.Append("\n## Not read\n\n").AppendJoin('\n', unread.Select(u => $"- {u}")).Append('\n');
        files["index.md"] = head.ToString();

        var removed = WorkflowFiles.Sweep(dir, files.Keys, Marker);
        foreach (var (name, text) in files)
        {
            var path = Path.Combine(dir, name);
            if (!File.Exists(path) || File.ReadAllText(path) != text) Quotes.WriteAtomic(path, text);
        }
        return new JsonObject
        {
            ["written"] = true, ["out"] = Path.GetRelativePath(root, dir).Replace('\\', '/'), ["files"] = files.Count, ["removed"] = removed,
            ["testFiles"] = rows.Count, ["otherRunnersTests"] = notBrowser, ["tests"] = totals.Tests, ["hooks"] = totals.Hooks, ["steps"] = totals.Steps, ["unknown"] = totals.Unknown,
            ["gotos"] = totals.Gotos, ["gotosResolved"] = totals.GotosResolved, ["gotosToReferencePage"] = totals.ToReference,
            ["unknownByReason"] = new JsonObject(totals.ByReason.OrderBy(r => r.Key, StringComparer.Ordinal).Select(r => KeyValuePair.Create(r.Key, (JsonNode?)r.Value))),
            ["stepsByKind"] = new JsonObject(totals.ByKind.OrderBy(k => k.Key, StringComparer.Ordinal).Select(k => KeyValuePair.Create(k.Key, (JsonNode?)k.Value))),
            ["graphCommit"] = graph.Commit,
        };
    }

    static void RenderBlock(StringBuilder sb, JsonObject block, string spec, Totals totals, string outFile, List<Node> pages, List<string> frontends, Dictionary<string, int> sameRoute, SpecIndex index)
    {
        var kind = (string)block["kind"]!;
        var titles = block["titles"]!.AsArray().Select(t => (string)t!).ToList();
        var name = string.Join(" › ", titles);
        if (kind == "test") totals.Tests++;
        else totals.Hooks++;
        var heading = kind switch
        {
            "test" => name,
            "beforeEach" => $"Before each test{In(name)}",
            "afterEach" => $"After each test{In(name)}",
            "beforeAll" => $"Before all tests{In(name)}",
            _ => $"After all tests{In(name)}",
        };
        var mode = (string?)block["mode"];
        sb.Append($"\n## {heading}\n\nLine {(int)block["line"]!}{(mode is null ? "" : $", written as `test.{mode}`")}.\n");
        var steps = block["steps"]!.AsArray().OfType<JsonObject>().ToList();
        if (steps.Count == 0) sb.Append("\nNo steps.\n");
        else sb.Append('\n');
        for (var i = 0; i < steps.Count; i++) sb.Append($"{i + 1}. {Step(steps[i], spec, totals, outFile, pages, frontends, sameRoute, index)}\n");
    }

    static string In(string name) => name.Length == 0 ? " in this file" : $" in {name}";

    static string Step(JsonObject s, string spec, Totals totals, string outFile, List<Node> pages, List<string> frontends, Dictionary<string, int> sameRoute, SpecIndex index)
    {
        var kind = (string)s["kind"]!;
        var line = (int)s["line"]!;
        var written = (string)s["words"]!;
        // A local name followed: `expect(quantity)` says what quantity is, beside the test's own words.
        var words = Code(written) + ((string?)s["target"] is { } target && !written.Contains(target, StringComparison.Ordinal) && Known(s) ? $" = {Code(target)}" : "");
        var reason = (string?)s["reason"];
        totals.Steps++;
        totals.ByKind[kind] = totals.ByKind.GetValueOrDefault(kind) + 1;
        if (kind == "goto") return Goto(s, spec, words, line, totals, outFile, pages, frontends, sameRoute, index);
        if (reason is not null)
        {
            totals.Count(reason);
            var inside = (int?)s["inside"] is { } n ? $" ({n} {Plural(n, "statement")} inside)" : "";
            return $"{Unknown} {(kind == "unknown" ? "" : $"{Verb(kind)}: ")}{words} (line {line}): {reason}{inside}";
        }
        return $"{Verb(kind)}: {words} (line {line})";
    }

    static bool Known(JsonObject s) => s["reason"] is null;

    static string Goto(JsonObject s, string spec, string words, int line, Totals totals, string outFile, List<Node> pages, List<string> frontends, Dictionary<string, int> sameRoute, SpecIndex index)
    {
        totals.Gotos++;
        var (screens, why) = PlaywrightDetector.Resolve(pages, frontends, spec, new SpecGoto(line, (string?)s["receiver"] ?? "", (string?)s["url"]));
        if (why is not null)
        {
            totals.Count(GotoNotResolved);
            return $"{Unknown} {Verb("goto")}: {words} (line {line}): no page resolved. {why}";
        }
        totals.GotosResolved++;
        var linked = screens.Select(p => (Page: p, Id: PageList.ScreenId(p, sameRoute[p.Name]))).ToList();
        var found = linked.Where(x => index.PageFiles.ContainsKey(x.Id)).ToList();
        if (found.Count > 0) totals.ToReference++;
        var to = linked.Select(x => index.PageFiles.TryGetValue(x.Id, out var file)
            ? $"[{x.Page.Name}]({Path.GetRelativePath(Path.GetDirectoryName(outFile)!, Path.ChangeExtension(file, ".md")).Replace('\\', '/')})"
            : $"screen {Code(x.Page.Name)}, no reference page yet");
        return $"{Verb("goto")}: {words} (line {line}) → {string.Join("; ", to)}";
    }

    static string Verb(string kind) => kind switch
    {
        "goto" => "**Go to**",
        "click" => "**Click**",
        "fill" => "**Fill in**",
        "select" => "**Select**",
        "check" => "**Check**",
        "wait" => "Wait",
        "read" => "Read",
        _ => "Do",
    };

    /// <summary>The words as code, in a fence longer than any backticks they hold.</summary>
    static string Code(string words)
    {
        var longest = 0;
        var run = 0;
        foreach (var c in words)
        {
            run = c == '`' ? run + 1 : 0;
            longest = Math.Max(longest, run);
        }
        var fence = new string('`', longest + 1);
        return longest == 0 ? $"`{words}`" : $"{fence} {words} {fence}";
    }

    static string Plural(int n, string word) => n == 1 ? word : word + "s";

    sealed class Totals
    {
        public int Tests, Hooks, Steps, Unknown, Gotos, GotosResolved, ToReference;
        public readonly Dictionary<string, int> ByKind = new(StringComparer.Ordinal);
        public readonly Dictionary<string, int> ByReason = new(StringComparer.Ordinal);

        public void Count(string reason)
        {
            Unknown++;
            ByReason[reason] = ByReason.GetValueOrDefault(reason) + 1;
        }

        public void Add(Totals other)
        {
            Tests += other.Tests;
            Hooks += other.Hooks;
            Steps += other.Steps;
            Unknown += other.Unknown;
            Gotos += other.Gotos;
            GotosResolved += other.GotosResolved;
            ToReference += other.ToReference;
            foreach (var (k, n) in other.ByKind) ByKind[k] = ByKind.GetValueOrDefault(k) + n;
            foreach (var (k, n) in other.ByReason) ByReason[k] = ByReason.GetValueOrDefault(k) + n;
        }

        public string Line() => $"{Tests} {Plural(Tests, "test")}, {Steps} {Plural(Steps, "step")}, {Unknown} {TestJourneys.Unknown}.";
    }
}
