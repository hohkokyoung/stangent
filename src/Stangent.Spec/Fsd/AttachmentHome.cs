namespace Stangent.Spec.Fsd;

/// <summary>
/// I.8: a file attached to a whole PDF, or one nothing in a Word body points to, has no section, so no link or check can reach it. With this on, those files get a
/// section at the document's end, made by code and saying what it is. Off by default: a document that has such files gains a section, which is new text and a new hash.
/// No section is guessed from a file's name or content. A document read flat has one section already, and that's the home.
/// </summary>
public static class AttachmentHome
{
    public const string Component = "attachment-home";
    public const string Title = "Files attached to this document";

    public static ConvertedDocument Apply(ConvertedDocument doc, bool on)
    {
        if (!on || doc.Attachments.All(a => a.Section is not null)) return doc;
        var flat = doc.Sections is [{ Id: FsdSections.FlatId }];
        var id = flat ? FsdSections.FlatId : NextId(doc);
        var attachments = doc.Attachments.Select(a => a.Section is null ? a with { Section = id } : a).ToList();
        if (flat) return doc with { Attachments = attachments };

        var text = "This section is generated by stangent: these files came with the document, which names no place in its text for them.\n\n"
            + string.Join('\n', doc.Attachments.Where(a => a.Section is null).Select(a => $"- {a.FileName}"));
        var markdown = doc.Markdown.TrimEnd('\n') + $"\n\n# {Title}\n\n{text}\n";
        var line = doc.Markdown.TrimEnd('\n').Count(c => c == '\n') + 3;
        return doc with
        {
            Markdown = markdown,
            Sections = [.. doc.Sections, new FsdSection(id, IdKind(doc), Title, 1, null, text, line)],
            Attachments = attachments,
        };
    }

    /// <summary>The next top-level number when the document numbers its sections; otherwise its heading, as such a document's ids are.</summary>
    static string NextId(ConvertedDocument doc)
    {
        var numbers = doc.Sections.Where(s => s.Parent is null && int.TryParse(s.Id, out _)).Select(s => int.Parse(s.Id)).ToList();
        return numbers.Count > 0 ? (numbers.Max() + 1).ToString(System.Globalization.CultureInfo.InvariantCulture) : Title;
    }

    static string IdKind(ConvertedDocument doc) => doc.Sections.FirstOrDefault(s => s.Parent is null && int.TryParse(s.Id, out _))?.IdKind ?? doc.Sections.FirstOrDefault()?.IdKind ?? "path";
}
