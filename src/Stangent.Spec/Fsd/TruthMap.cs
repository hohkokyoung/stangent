    const int StepsShown = 30;
    const int ScenariosShown = 20;

    /// <summary>The same as the JSON, for the PM, in plain words (D371): how to answer, the numbered questions still open
    /// (medium and low matches first), each section's text with its numbered entries, the code no section covers, then the
    /// flows linked. No syntax to learn: the PM tells Claude "12 yes, 13 the FSD is right".</summary>
    public static string Markdown(JsonObject map)
    {
        var sb = new StringBuilder(Marker).Append("\n\n");
        var doc = (string)map["doc"]!;
        sb.Append($"# Truth map: {(string)map["title"]!} (`{doc}`)\n\n");
        sb.Append($"Questions numbered for map `{PmAnswers.MapId(map)}`.\n\n");
        sb.Append("## How to answer\n\n");
        sb.Append($"Read the numbered questions below and tell Claude your answers in plain words: in Claude Code in this repo, run `/stangent:rule {doc}`, ")
            .Append("then say, for example, \"12 yes, 13 the FSD is right, 14 keep it\". Claude records each answer and reads it back to you; ")
            .Append("to change one, answer its number again. Your answers count once they are committed. You never edit `rulings.yaml`.\n\n");

        var runs = (int)map["review"]!["runs"]!;
        var sections = map["sections"]!.AsArray().OfType<JsonObject>().ToList();
        var loose = map["undocumented"]!.AsArray().OfType<JsonObject>().ToList();
        var all = sections.SelectMany(s => s["entries"]!.AsArray().OfType<JsonObject>().Select(e => ((JsonObject?)s, e))).Concat(loose.Select(e => ((JsonObject?)null, e))).ToList();
        var verify = all.Where(x => (string)x.e["standing"]! == "unconfirmed" && (string?)x.e["confidence"] is "low" or "medium")
            .OrderBy(x => (string?)x.e["confidence"] == "low" ? 0 : 1).ThenBy(x => (int)x.e["n"]!).ToList();
        var again = all.Where(x => (string)x.e["standing"]! is "flagged" or "not-found").ToList();
        var blank = all.Where(x => (string)x.e["standing"]! == "blank").ToList();
        var toConfirm = sections.Where(OpenMatches).ToList();
        var open = verify.Count + again.Count + blank.Count + toConfirm.Count;
        sb.Append($"## Still to answer ({open})\n\n");
        if (open == 0) sb.Append("Nothing: every question is answered.\n\n");
        void List(string title, IEnumerable<string> lines)
        {
            var l = lines.ToList();
            if (l.Count == 0) return;
            sb.Append($"### {title}\n\n");
            foreach (var line in l) sb.Append($"- {line}\n");
            sb.Append('\n');
        }
        List("Check these matches first (medium and low confidence)", verify.Select(x => $"**{(int)x.e["n"]!}.** {Where(x.Item1)} · {(string)x.e["confidence"]!} · {Quote(x.e)} Does the code do what the FSD says?"));
        List("Look at these again", again.Select(x => $"**{(int)x.e["n"]!}.** {Where(x.Item1)} · {Short(x.e)} · {Standing(x.e)}"));
        List("Not answered yet", blank.Select(x => $"**{(int)x.e["n"]!}.** {Where(x.Item1)} · {Short(x.e)}"));
        List("Sections whose matches aren't confirmed", toConfirm.Select(s => $"**{(int)s["matches"]!["n"]!}.** {Heading(s)}: are its {Count((int)s["matches"]!["count"]!, "match", "matches")} right?"));

        var review = map["review"]!;
        var c = map["counts"]!.AsObject();
        var links = map["links"]!;
        sb.Append("## About this map\n\n");
        sb.Append($"- From the review of commit `{(string)review["commit"]!}` (FSD version `{(string)review["fsdVersion"]!}`, {(int)review["runs"]!} runs).\n");
        sb.Append($"- {(int)c["entries"]!} items: {(int)c["ruled"]!} answered, {(int)c["blank"]!} not answered yet, {(int)c["flagged"]!} to look at again, {(int)c["not-found"]!} the last review didn't find again; ")
            .Append($"matches: {(int)c["confirmed"]!} confirmed, {(int)c["unconfirmed"]!} to confirm ({(int)c["unconfirmedMatches"]!["low"]!} low, {(int)c["unconfirmedMatches"]!["medium"]!} medium confidence), {(int)c["not-a-match"]!} answered no.\n");
        sb.Append($"- Linked to code by flow {(int)links["flow"]!}, screen {(int)links["screen"]!}, node {(int)links["node"]!}, file {(int)links["file"]!}")
            .Append(FormattableString.Invariant($" ({(double)links["fallbackShare"]!:0.0}% by fallback, a node or file rather than a flow or screen).\n"));
        sb.Append("- Who answered and when come from git; _not committed_ means the answer isn't in a commit yet.\n");
        sb.Append("- Each item rests on an AI's reading of the code, checked by code for its quote and lines only. A ticket that rests on a match of medium or low confidence stops until you confirm it.\n\n");

        foreach (var s in sections)
        {
            var entries = s["entries"]!.AsArray().OfType<JsonObject>().ToList();
            var text = (string?)s["text"];
            if (entries.Count == 0 && string.IsNullOrWhiteSpace(text)) continue;
            sb.Append($"## {Heading(s)}\n\n");
            if (text is null) sb.Append("_This section isn't in the FSD any more; its answers are kept until you drop them._\n\n");
            else if (!string.IsNullOrWhiteSpace(text)) sb.Append(string.Join("\n", text.TrimEnd().Split('\n').Select(l => l.Length == 0 ? ">" : "> " + l))).Append("\n\n");
            if (entries.Count == 0) { sb.Append("The review found nothing here.\n\n"); continue; }
            var m = s["matches"]!;
            if ((int?)m["n"] is { } mn)
            {
                var places = Count((int)m["count"]!, "place", "places");
                sb.Append(OpenMatches(s)
                    // Open, even in a confirmed section when a match was added since (shown as new below).
                    ? $"**{mn}.** The code does what this section says in {places} (below){((bool)m["confirmed"]! ? $", confirmed {By(m)} before a new one came" : "")}. "
                        + ((int)m["count"]! == 1 ? "**Is it right?** `yes`, or answer `no` on it" : "**Are they all right?** `yes`, or answer `no` on the one that isn't") + ".\n\n"
                    : (bool)m["confirmed"]! ? $"**{mn}.** The code does what this section says in {places}: confirmed {By(m)}.\n\n"
                    : $"**{mn}.** The code does what this section says in {places}: each answered below.\n\n");
            }
            WriteEntries(sb, entries, runs);
        }
        if (loose.Count > 0)
        {
            sb.Append("## Code no section covers\n\n");
            WriteEntries(sb, loose, runs);
        }
        var flows = map["flows"]!.AsObject();
        if (flows.Count > 0)
        {
            sb.Append("## Flows linked above\n\n");
            foreach (var (id, node) in flows)
            {
                var f = node!.AsObject();
                sb.Append($"### {(string)f["name"]!} (`{id}`)\n\n");
                if (f["actor"] is JsonObject a) sb.Append($"- Who: {(string?)a["who"]}{((string?)a["why"] is { } why ? $" ({why})" : "")}\n");
                var steps = f["steps"]!.AsArray().OfType<JsonObject>().ToList();
                sb.Append($"- {steps.Count} steps, 🟡 {(int)f["guesses"]!}, ❓ {(int)f["unknowns"]!} · `{(string)f["file"]!}`\n");
                foreach (var (st, i) in steps.Take(StepsShown).Select((st, i) => (st, i)))
                {
                    var cond = st["conditions"]!.AsArray().Select(x => (string)x!).Where(x => x.Length > 0).ToList();
                    sb.Append($"  {i + 1}. {(string?)st["what"]}{(cond.Count > 0 ? $" — when `{string.Join("`, `", cond)}`" : "")} (`{(string?)st["at"]}`)\n");
                }
                if (steps.Count > StepsShown) sb.Append($"  - … and {steps.Count - StepsShown} more steps, in `{(string)f["file"]!}`\n");
                var scenarios = f["scenarios"]!.AsArray().OfType<JsonObject>().ToList();
                if (scenarios.Count > 0)
                {
                    sb.Append($"- Scenarios ({scenarios.Count}):\n");
                    foreach (var sc in scenarios.Take(ScenariosShown))
                    {
                        var cond = sc["conditions"]!.AsArray().Select(x => (string)x!).Where(x => x.Length > 0).ToList();
                        sb.Append($"  - {(string?)sc["name"]}{(cond.Count > 0 ? $": `{string.Join("`, `", cond)}`" : "")}\n");
                    }
                    if (scenarios.Count > ScenariosShown) sb.Append($"  - … and {scenarios.Count - ScenariosShown} more, in `{(string)f["file"]!}`\n");
                }
                sb.Append('\n');
            }
        }
        return sb.ToString().TrimEnd('\n') + "\n";
    }

    /// <summary>A section with a match nobody has answered: its question is still open.</summary>
    static bool OpenMatches(JsonObject s) => (int?)s["matches"]!["n"] is not null
        && s["entries"]!.AsArray().OfType<JsonObject>().Any(e => (string)e["state"]! == "match" && (string)e["standing"]! == "unconfirmed");

    static string Count(int n, string one, string many) => $"{n} {(n == 1 ? one : many)}";

    static string Where(JsonObject? section) => section is null ? "Code no section covers" : Heading(section);

    /// <summary>What the review found, in plain words.</summary>
    public static string StateWords(string state) => state switch
    {
        "gap" => "The FSD says it; the code doesn't do it",
        "conflict" => "The FSD and the code disagree",
        "undocumented" => "The code does this; the FSD doesn't say",
        _ => "The code does what the FSD says",
    };

    /// <summary>A ruling in plain words.</summary>
    public static string RulingWords(string ruling) => ruling switch
    {
        "code-right" => "the code is right (the FSD needs updating)",
        "fsd-right" => "the FSD is right (the code has a bug)",
        "restated" => "neither as written: the rule in your words",
        "keep" => "keep this code",
        "remove" => "remove this code",
        "confirmed" => "yes, the code does what the FSD says",
        "not-a-match" => "no, the code doesn't do what the FSD says",
        _ => ruling,
    };

    /// <summary>The question for an entry and its answers.</summary>
    static string Question(string state) => state switch
    {
        "match" => "**Does the code do what the FSD says?** `yes` · `no`",
        "undocumented" => "**The FSD doesn't mention this. Keep it?** `keep` · `remove` · or the rule in your own words",
        _ => "**Which is right?** `code`: the code is right, the FSD needs updating · `fsd`: the FSD is right, the code has a bug · or the rule in your own words",
    };

    static string Short(JsonObject e) => e["key"]!["quote"] is not null ? $"{StateWords((string)e["state"]!)}: {Quote(e)}" : $"{StateWords((string)e["state"]!)}: {Code(e)}";

    static string Standing(JsonObject e)
    {
        var ruling = (string?)e["ruling"];
        var was = ruling is null ? "" : $" (answered: {RulingWords(ruling)} {By(e)})";
        return (string)e["standing"]! switch
        {
            "ruled" => $"answered: **{RulingWords(ruling!)}** {By(e)}",
            "confirmed" => ruling is null ? "confirmed with its section" : $"answered: **{RulingWords(ruling)}** {By(e)}",
            "not-a-match" => $"answered: **{RulingWords("not-a-match")}** {By(e)}",
            "unconfirmed" => "not confirmed yet",
            "blank" => "**not answered yet**",
            "flagged" => $"**look again**: {FlagWords((string)e["flagged"]!)}{was}",
            _ => $"**the review of `{(string)e["notFound"]!}` didn't find this again**{was}; answer `drop` to remove it",
        };
    }

    /// <summary>Why an item needs another look, in plain words (the reasons <c>fsd rulings</c> writes).</summary>
    static string FlagWords(string flag)
    {
        if (flag == Rulings.LinkChanged) return "the code it points at changed since it was answered";
        if (FlagReason().Match(flag) is { Success: true } m)
        {
            var what = m.Groups["why"].Value == "FSD section changed" ? "this FSD section changed" : "the FSD's sentence changed";
            return m.Groups["was"].Success
                ? $"{what} since it was answered (the answer was: {RulingWords(m.Groups["was"].Value)})"
                : $"{what} since this section's matches were confirmed";
        }
        if (StateFlag().Match(flag) is { Success: true } k)
            return $"the review now says \"{StateWords(k.Groups["now"].Value)}\"; it said \"{StateWords(k.Groups["was"].Value)}\", answered: {RulingWords(k.Groups["r"].Value)}";
        return flag;
    }

    [GeneratedRegex(@"^(?<why>FSD section changed|its FSD quote is no longer in the section) since (?:ruled \(was (?<was>[a-z-]+)\)|its matches were confirmed)$")]
    private static partial Regex FlagReason();

    [GeneratedRegex(@"^the review now calls this a (?<now>[a-z]+); it was a (?<was>[a-z]+), ruled (?<r>[a-z-]+)$")]
    private static partial Regex StateFlag();

    static void WriteEntries(StringBuilder sb, List<JsonObject> entries, int runs)
    {
        foreach (var e in entries)
        {
            var state = (string)e["state"]!;
            var standing = (string)e["standing"]!;
            sb.Append($"**{(int)e["n"]!}.** {StateWords(state)}");
            if ((string?)e["confidence"] is { } conf) sb.Append($" ({conf} confidence)");
            sb.Append(" · ").Append(Standing(e));
            if ((bool)e["inFsd"]!) sb.Append(" · the FSD says your words now");
            if ((bool)e["new"]!) sb.Append(" · **new** since this section's matches were confirmed");
            sb.Append("\n\n");
            if (e["key"]!["quote"] is not null) sb.Append($"- The FSD says: {Quote(e)}\n");
            foreach (var n in e["notes"]!.AsArray()) sb.Append($"- The review: {(string)n!}\n");
            if ((string?)e["statement"] is { } st) sb.Append($"- Your words: {st}\n");
            if ((string?)e["pmNote"] is { } pm) sb.Append($"- Your note: {pm}\n");
            sb.Append($"- The code: {Code(e)} · {Found(e, runs)}{((bool)e["disagrees"]! ? " · the runs disagree: one called it a match" : "")}\n");
            if (standing is "blank" or "unconfirmed" or "flagged") sb.Append($"- {Question(state)}\n");
            sb.Append('\n');
        }
    }

    static string Heading(JsonObject s) => (string?)s["idKind"] == "number" ? $"{(string)s["section"]!} {(string)s["title"]!}" : (string)s["title"]!;

    static string Quote(JsonObject e) => (string?)e["key"]!["quote"] is { } q ? $"“{Quotes.Normalize(q)}”" : "";

    static string Code(JsonObject e)
    {
        var link = e["link"]!;
        var kind = (string)link["kind"]!;
        var lines = string.Join(", ", e["evidence"]!.AsArray().Select(v => $"`{(string)v!}`"));
        return $"{(lines.Length > 0 ? lines : "no lines")} → {kind} `{(string)link["id"]!}`{(kind is "flow" or "screen" ? $" ({(string)link["title"]!})" : "")}";
    }

    static string Found(JsonObject e, int runs)
    {
        var mine = e["runs"]!.AsArray().Select(r => (int)r!).ToList();
        var found = runs > 0 && mine.Count >= runs ? "found by every run" : $"found by run {string.Join(", ", mine)} of {runs}";
        return found + ((bool)e["fallback"]! ? ", linked by fallback" : "");
    }

    static string By(JsonNode n) => (bool?)n["committed"] == false ? "(_not committed_)" : (string?)n["by"] is { } by ? $"by {by} on {(string?)n["on"]}" : "";
}
