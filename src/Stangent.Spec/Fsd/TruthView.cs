    /// <summary>A question's headline: the review's first note (what the app does), else the spec's sentence, cut at a word.</summary>
    static string Headline(JsonObject e)
    {
        var note = e["notes"]!.AsArray().Select(x => (string?)x).FirstOrDefault(x => !string.IsNullOrWhiteSpace(x));
        return Cut(note ?? Quotes.Normalize((string?)e["key"]!["quote"] ?? LinkTitle(e)), 110);
    }

    static string ListedLine(JsonObject e)
    {
        var note = e["notes"]!.AsArray().Select(x => (string?)x).FirstOrDefault(x => !string.IsNullOrWhiteSpace(x)) ?? LinkTitle(e);
        var standing = (string)e["standing"]! == "blank" && (bool?)e["needsWords"] != true ? "" : $" · {TruthMap.StandingWords(e)}";
        return $"{note} (#{(int)e["n"]!}){standing}";
    }

    /// <summary>A module's question numbers: "21–24", "21", or "–".</summary>
    static string Numbers(Module m)
    {
        var ns = Questions(m).Select(e => (int)e["n"]!).ToList();
        if (m.Section is { } s && (int?)s["matches"]!["n"] is { } mn) ns.Add(mn);
        if (ns.Count == 0) return "–";
        var (lo, hi) = (ns.Min(), ns.Max());
        return lo == hi ? lo.ToString(CultureInfo.InvariantCulture) : $"{lo}–{hi}";
    }

    static string Cut(string text, int max)
    {
        var t = Regex.Replace(text, @"\s+", " ").Trim();
        if (t.Length <= max) return t;
        var cut = t[..max];
        var space = cut.LastIndexOf(' ');
        return (space > max / 2 ? cut[..space] : cut).TrimEnd(',', ';', ':', '.') + "…";
    }

    static string Cell(string s) => s.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
    /// <summary>Text for a link's brackets: a table cell's escapes, and its own brackets escaped so the link holds.</summary>
    static string LinkText(string s) => Cell(s).Replace("[", "\\[", StringComparison.Ordinal).Replace("]", "\\]", StringComparison.Ordinal);
    /// <summary>Code for a one-backtick span: a backtick inside would end it, so it becomes a quote mark; a cell's escapes too.</summary>
    static string Code(string s) => Cell(s).Replace('`', '\'');
    static string Dash(int n) => n == 0 ? "–" : n.ToString(CultureInfo.InvariantCulture);
    static string Short(string? hash) => (hash ?? "").Replace("sha256:", "", StringComparison.Ordinal) is var h && h.Length > 8 ? h[..8] : h;
    static string Plural(int n, string one, string many) => $"{n} {(n == 1 ? one : many)}";
