/// <summary>
/// The PM's view of the truth map (D415), written by code from <c>truth-map.json</c> at <c>fsd rulings-check</c>, the same
/// bytes from the same inputs: <c>specs/fsd/index.md</c> at the root of the mapping (every document, its open questions and
/// its areas), then per document one folder per area under <c>specs/fsd/&lt;doc&gt;/view/</c> (an FSD top-level chapter; the
/// code no section covers is one more area, by screen) holding <c>summary.md</c> and one file per module (a section with
/// text of its own): its text, then only its questions. A question says what the review found in the spec's words and the
/// app's, how sure, what each answer causes, and, for a linked flow worded by D416, its actor, journey, edge cases and a
/// chart drawn by code; the code itself is folded at the bottom for developers. Listed controls (D414) are listed with
/// their number, never asked.
/// </summary>
public static partial class TruthView
{
    public const string Folder = "view";
    public const string IndexName = "index.md";

    public static string IndexPath(string root) => Path.Combine(root, "specs", "fsd", IndexName);
    public static string ViewDir(string root, string doc) => Path.Combine(FsdImport.DocDir(root, doc), Folder);

    static string Marker(string doc) =>
        $"<!-- Generated by `stangent fsd rulings-check` (D415): never read back. To answer, tell Claude the numbers (`/stangent:rule {doc}`). -->";

    const string IndexMarker = "<!-- Generated by `stangent fsd rulings-check` (D415): never read back. Each document's questions are answered by number (`/stangent:rule <doc>`). -->";

    static string Rel(string root, string path) => Path.GetRelativePath(root, path).Replace('\\', '/');

    // ---- the model ---------------------------------------------------------------------------------------------------------

    internal sealed record Module(JsonObject? Section, string Title, string File, List<JsonObject> Entries);
    internal sealed record Area(string Folder, string Title, List<Module> Modules);

    /// <summary>The document's areas in FSD order: one per top-level chapter, holding its sections with text or entries; then
    /// the code no section covers, one module per screen (its link's title).</summary>
    internal static List<Area> Areas(JsonObject map)
    {
        var areas = new List<Area>();
        Area? current = null;
        var k = 0;
        var m = 0;
        foreach (var s in map["sections"]!.AsArray().OfType<JsonObject>())
        {
            if (current is null || ((int?)s["level"] ?? 1) <= 1)
            {
                current = new Area($"{++k:00}-{Slug(TruthMap.Heading(s))}", TruthMap.Heading(s), []);
                areas.Add(current);
            }
            var entries = s["entries"]!.AsArray().OfType<JsonObject>().ToList();
            m++;
            if (entries.Count == 0 && string.IsNullOrWhiteSpace((string?)s["text"])) continue;
            var name = (string?)s["idKind"] == "number" ? (string)s["section"]! : $"m{m:000}";
            current.Modules.Add(new Module(s, TruthMap.Heading(s), Unique(current, $"{name}-{Slug((string)s["title"]!)}.md"), entries));
        }
        areas.RemoveAll(a => a.Modules.Count == 0);
        var loose = map["undocumented"]!.AsArray().OfType<JsonObject>().ToList();
        if (loose.Count > 0)
        {
            var area = new Area("zz-not-in-the-spec", "Not in the spec", []);
            foreach (var g in loose.GroupBy(LinkTitle, StringComparer.Ordinal).OrderBy(g => g.Key, StringComparer.Ordinal))
                area.Modules.Add(new Module(null, g.Key, Unique(area, $"screen-{Slug(g.Key)}.md"), [.. g]));
            areas.Add(area);
        }
        return areas;
    }

    static string Unique(Area area, string file)
    {
        var name = file;
        for (var i = 2; area.Modules.Any(x => x.File == name); i++) name = file[..^3] + $"-{i}.md";
        return name;
    }

    static string LinkTitle(JsonObject e)
    {
        var link = e["link"]!;
        var title = (string?)link["title"];
        return string.IsNullOrWhiteSpace(title) ? (string)link["id"]! : title;
    }

    /// <summary>Lower case, words joined by hyphens, at most 50 characters: <c>7 Reading lists</c> → <c>7-reading-lists</c>.</summary>
    internal static string Slug(string text)
    {
        var s = SlugRun().Replace(text.ToLowerInvariant(), "-").Trim('-');
        if (s.Length > 50) s = s[..50].TrimEnd('-');
        return s.Length == 0 ? "section" : s;
    }

    [GeneratedRegex("[^a-z0-9]+")]
    private static partial Regex SlugRun();

    internal static bool Listed(JsonObject e) => (bool?)e["onDemand"] == true;
    static bool IsMatch(JsonObject e) => (string)e["state"]! == "match";
    static bool Open(JsonObject e) => (string)e["standing"]! is "blank" or "flagged" or "not-found";

    /// <summary>A section with a match nobody has answered: its question is still open.</summary>
    static bool OpenMatches(JsonObject? s) => s is not null && (int?)s["matches"]!["n"] is not null
        && s["entries"]!.AsArray().OfType<JsonObject>().Any(e => IsMatch(e) && (string)e["standing"]! == "unconfirmed");

    /// <summary>The questions a module asks: its section's matches (one question), then each entry not listed and not a match
    /// (a match flagged or not found again is asked on its own too).</summary>
    internal static IEnumerable<JsonObject> Questions(Module m) =>
        m.Entries.Where(e => !Listed(e) && (!IsMatch(e) || (string)e["standing"]! is "flagged" or "not-found"));

    sealed record Tally(int Questions, int Open, int Answered, int Listed);

    static Tally Count(Module m)
    {
        var qs = Questions(m).ToList();
        var matches = m.Section is { } s && (int?)s["matches"]!["n"] is not null;
        var open = qs.Count(Open) + (OpenMatches(m.Section) ? 1 : 0);
        var all = qs.Count + (matches ? 1 : 0);
        return new Tally(all, open, all - open, m.Entries.Count(Listed));
    }

    static Tally Count(IEnumerable<Module> ms) => ms.Select(Count).Aggregate(new Tally(0, 0, 0, 0), (a, b) => new(a.Questions + b.Questions, a.Open + b.Open, a.Answered + b.Answered, a.Listed + b.Listed));

    /// <summary>The flows the view's questions link to, picked by D416's rules, and their words when the words were checked
    /// against the same picks.</summary>
    internal sealed class Flows(string root, string doc, JsonObject map)
    {
        readonly Dictionary<string, JsonObject> index = FlowWords.FlowIndex(root);
        readonly Dictionary<string, FlowWords.Picked?> picks = new(StringComparer.Ordinal);
        readonly JsonObject words = FlowWords.LoadWords(root, doc);
        public string Doc { get; } = doc;
        public JsonObject Map { get; } = map;

        public FlowWords.Picked? Pick(string id)
        {
            if (picks.TryGetValue(id, out var p)) return p;
            return picks[id] = index.TryGetValue(id, out var entry) ? FlowWords.Pick(root, entry) : null;
        }

        public FlowWords.Worded? Words(FlowWords.Picked p) => FlowWords.WordsFor(words, p);
    }

    static IEnumerable<string> LinkedFlows(IEnumerable<JsonObject> entries) =>
        entries.Where(e => (string)e["link"]!["kind"]! == "flow").Select(e => (string)e["link"]!["id"]!).Distinct(StringComparer.Ordinal);

    /// <summary>The whole view as one text, in reading order: the index, then each area's summary and its modules. For Claude
    /// to read before answering (<c>/stangent:rule</c>) and for checks; empty when there is no view.</summary>
    public static string ReadAll(string root, string doc)
    {
        var sb = new StringBuilder();
        if (File.Exists(IndexPath(root))) sb.Append(File.ReadAllText(IndexPath(root))).Append('\n');
        var dir = ViewDir(root, doc);
        if (!Directory.Exists(dir)) return sb.ToString();
        foreach (var area in Directory.GetDirectories(dir).Order(StringComparer.Ordinal))
        {
            var summary = Path.Combine(area, "summary.md");
            if (File.Exists(summary)) sb.Append(File.ReadAllText(summary)).Append('\n');
            foreach (var f in Directory.GetFiles(area, "*.md").Where(f => Path.GetFileName(f) != "summary.md").Order(StringComparer.Ordinal))
                sb.Append(File.ReadAllText(f)).Append('\n');
        }
        return sb.ToString();
    }

    // ---- writing ---------------------------------------------------------------------------------------------------------

    /// <summary>The document's view folder, rewritten from nothing, and the root index. Returns what was written.</summary>
    public static JsonObject Write(string root, string doc, JsonObject map)
    {
        var dir = ViewDir(root, doc);
        if (Directory.Exists(dir)) Directory.Delete(dir, recursive: true);
        Directory.CreateDirectory(dir);
        var flows = new Flows(root, doc, map);
        var areas = Areas(map);
        var files = new JsonArray();
        foreach (var area in areas)
        {
            var folder = Path.Combine(dir, area.Folder);
            Directory.CreateDirectory(folder);
            Quotes.WriteAtomic(Path.Combine(folder, "summary.md"), Summary(area, flows));
            files.Add((JsonNode)Rel(root, Path.Combine(folder, "summary.md")));
            foreach (var m in area.Modules)
            {
                Quotes.WriteAtomic(Path.Combine(folder, m.File), ModuleFile(area, m, flows));
                files.Add((JsonNode)Rel(root, Path.Combine(folder, m.File)));
            }
        }
        WriteIndex(root);
        return new JsonObject
        {
            ["index"] = Rel(root, IndexPath(root)), ["folder"] = Rel(root, dir), ["areas"] = areas.Count,
            ["modules"] = areas.Sum(a => a.Modules.Count), ["files"] = files,
        };
    }

    /// <summary><c>specs/fsd/index.md</c> from every document's <c>truth-map.json</c>, in document order.</summary>
    public static void WriteIndex(string root)
    {
        var fsd = Path.Combine(root, "specs", "fsd");
        var maps = (Directory.Exists(fsd) ? Directory.GetDirectories(fsd) : [])
            .OrderBy(d => d, StringComparer.Ordinal)
            .Select(d => PageRun.LoadJson(Path.Combine(d, "truth-map.json")) as JsonObject)
            // Only maps of this version: an older one lacks what the view reads; its document is listed once rebuilt.
            .OfType<JsonObject>().Where(m => (string?)m["contract"] == TruthMap.Contract && (int?)m["version"] == TruthMap.Version && (string?)m["doc"] is not null).ToList();
        if (maps.Count == 0) return;
        Quotes.WriteAtomic(IndexPath(root), Index(root, maps));
    }

    static string Index(string root, List<JsonObject> maps)
    {
        var sb = new StringBuilder(IndexMarker).Append("\n\n# The spec and the code: index\n\n");
        var docs = maps.Select(m => (Map: m, Doc: (string)m["doc"]!, Areas: Areas(m), Flows: new Flows(root, (string)m["doc"]!, m))).ToList();
        var totals = docs.Select(d => Count(d.Areas.SelectMany(a => a.Modules))).ToList();
        var open = totals.Sum(t => t.Open);
        var answered = totals.Sum(t => t.Answered);
        sb.Append($"**{Plural(docs.Count, "document", "documents")}, {Plural(open, "question", "questions")} open, {answered} answered.** ")
            .Append("Each document's questions are answered by number: in Claude Code, run `/stangent:rule <doc>` and say, for example, \"21 fsd, 22 code\".\n\n");
        sb.Append("| Document | Compared | Open | Answered | Listed, no answer needed |\n|---|---|---|---|---|\n");
        foreach (var (d, t) in docs.Zip(totals))
        {
            var review = d.Map["review"]!;
            sb.Append($"| [{LinkText((string)d.Map["title"]!)}](#doc-{Slug(d.Doc)}) (`{d.Doc}`) | app `{Short((string?)review["commit"])}`, spec `{Short((string?)review["fsdVersion"])}` | {t.Open} | {t.Answered} | {t.Listed} |\n");
        }
        sb.Append('\n');

        // Actors across the app: the worded actor of every linked flow, with the areas it appears in.
        var actors = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);
        foreach (var d in docs)
            foreach (var a in d.Areas)
                foreach (var id in LinkedFlows(a.Modules.SelectMany(Questions)))
                    if (d.Flows.Pick(id) is { } p && d.Flows.Words(p) is { } w && w.Lines.TryGetValue("A", out var actor))
                        (actors.TryGetValue(actor, out var set) ? set : actors[actor] = new SortedSet<string>(StringComparer.Ordinal)).Add(a.Title);
        sb.Append("**Actors across the app:** ");
        sb.Append(actors.Count == 0
            ? "_none in plain words yet: they come from the linked flows once worded (`plugin/scripts/fsd-view-run.sh --max-cost <usd> <doc>`, D416)._\n\n"
            : string.Join(" · ", actors.Select(kv => $"{kv.Key} ({string.Join(", ", kv.Value)})")) + "\n\n");

        foreach (var (d, t) in docs.Zip(totals))
        {
            sb.Append($"<a id=\"doc-{Slug(d.Doc)}\"></a>\n\n## {(string)d.Map["title"]!}\n\n");
            var built = Directory.Exists(ViewDir(root, d.Doc));
            if (!built) sb.Append($"_Its view isn't written yet: run `stangent fsd rulings-check {d.Doc}`._\n\n");
            sb.Append($"`{d.Doc}` · questions numbered for map `{PmAnswers.MapId(d.Map)}` · {Plural(t.Open, "question", "questions")} open, {t.Answered} answered, {t.Listed} listed.\n\n");
            var all = d.Areas.SelectMany(a => a.Modules).ToList();
            sb.Append("| Kind | Open | Answered | What you decide |\n|---|---|---|---|\n");
            foreach (var (state, label, decide) in Kinds)
            {
                var qs = all.SelectMany(Questions).Where(e => (string)e["state"]! == state && !IsMatch(e)).ToList();
                sb.Append($"| {label} | {qs.Count(Open)} | {qs.Count(e => !Open(e))} | {decide} |\n");
            }
            var sections = all.Where(m => m.Section is { } s && (int?)s["matches"]!["n"] is not null).ToList();
            sb.Append($"| **Looks right**: sentences the app seems to follow, one answer per section | {sections.Count(m => OpenMatches(m.Section))} | {sections.Count(m => !OpenMatches(m.Section))} | Confirm them, or name the one that's wrong |\n\n");
            sb.Append("| Area | Not built | Different | Not in spec | Looks right | Listed | Open |\n|---|---|---|---|---|---|---|\n");
            foreach (var a in d.Areas)
            {
                var qs = a.Modules.SelectMany(Questions).ToList();
                int Of(string state) => qs.Count(e => (string)e["state"]! == state && !IsMatch(e));
                var at = Count(a.Modules);
                var link = $"{d.Doc}/{Folder}/{a.Folder}/summary.md";
                sb.Append($"| {(built ? $"[{LinkText(a.Title)}]({link})" : Cell(a.Title))} | {Dash(Of("gap"))} | {Dash(Of("conflict"))} | {Dash(Of("undocumented"))} | {Dash(a.Modules.Count(m => m.Section is { } s && (int?)s["matches"]!["n"] is not null))} | {Dash(at.Listed)} | {at.Open} |\n");
            }
            sb.Append('\n');
        }
        return sb.ToString().TrimEnd('\n') + "\n";
    }

    static readonly (string State, string Label, string Decide)[] Kinds =
    [
        ("gap", "**Promised, not built**: the spec says it, the app doesn't have it", "Is it still wanted?"),
        ("conflict", "**Built differently**: the app does it another way", "Which is right, the spec or the app?"),
        ("undocumented", "**Built, not in the spec**: the spec never mentions it", "Keep it (and say what it does) or remove it?"),
    ];

    static string Summary(Area area, Flows flows)
    {
        var doc = flows.Doc;
        var sb = new StringBuilder(Marker(doc)).Append("\n\n");
        sb.Append($"# {area.Title}: summary\n\n");
        sb.Append($"[← index](../../../{IndexName}) · questions numbered for map `{PmAnswers.MapId(flows.Map)}`\n\n");
        var t = Count(area.Modules);
        sb.Append($"**{Plural(t.Questions, "question", "questions")}, {t.Open} still open, {t.Answered} answered.**");
        if (t.Listed > 0) sb.Append($" {t.Listed} listed, no answer needed.");
        sb.Append("\n\n| Module | Questions | Still open |\n|---|---|---|\n");
        foreach (var m in area.Modules)
        {
            var c = Count(m);
            sb.Append($"| [{LinkText(m.Title)}]({m.File}) | {Numbers(m)} | {c.Open} |\n");
        }
        sb.Append('\n');

        var questions = area.Modules.SelectMany(Questions).ToList();
        var linked = LinkedFlows(questions).Select(flows.Pick).OfType<FlowWords.Picked>().ToList();
        var worded = linked.Select(p => (p, w: flows.Words(p))).ToList();
        var actors = worded.Where(x => x.w is not null && x.w.Lines.ContainsKey("A")).Select(x => x.w!.Lines["A"]).Distinct(StringComparer.Ordinal).ToList();
        sb.Append("**Actors:** ").Append(actors.Count > 0 ? string.Join(" · ", actors)
            : linked.Count == 0 ? "_no question here links to a flow, so none is named._" : NotWorded(doc)).Append("\n\n");
        var screens = area.Modules.SelectMany(m => m.Entries)
            .Where(e => (string)e["link"]!["kind"]! == "screen" || ((string?)e["link"]!["title"])?.StartsWith('/') == true)
            .Select(LinkTitle).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList();
        if (screens.Count > 0) sb.Append("**Screens:** ").Append(string.Join(" · ", screens.Select(x => $"`{x}`"))).Append("\n\n");
        if (worded.Count > 0)
            sb.Append("**Journeys:** ").Append(string.Join(" · ", worded.Select(x => x.w?.Title is { Length: > 0 } title ? title : $"`{x.p.Name}` _(not in plain words yet)_"))).Append("\n\n");
        var asked = questions.Where(e => e["runs"]!.AsArray().Count > 0).ToList();
        var runs = (int)flows.Map["review"]!["runs"]!;
        if (asked.Count > 0)
            sb.Append($"**How sure:** {asked.Count(e => runs > 0 && e["runs"]!.AsArray().Count >= runs)} of {asked.Count} found by every review run.\n\n");

        var differences = area.Modules.SelectMany(m => Questions(m).Select(e => (m, e))).ToList();
        if (differences.Count > 0)
        {
            sb.Append("**In this area**\n\n");
            foreach (var (m, e) in differences)
                sb.Append($"- **{(int)e["n"]!}.** {KindLabel((string)e["state"]!)}: {Headline(e)} ([{LinkText(m.Title)}]({m.File})){(Open(e) ? "" : " · answered")}\n");
            foreach (var m in area.Modules.Where(m => m.Section is { } s && (int?)s["matches"]!["n"] is not null))
                sb.Append($"- **{(int)m.Section!["matches"]!["n"]!}.** Looks right: {Plural((int)m.Section["matches"]!["count"]!, "sentence", "sentences")} ([{LinkText(m.Title)}]({m.File})){(OpenMatches(m.Section) ? "" : " · answered")}\n");
            sb.Append('\n');
        }
        var listed = area.Modules.SelectMany(m => m.Entries.Where(Listed)).ToList();
        if (listed.Count > 0)
        {
            sb.Append("**Listed, no answer needed** (you're asked about one only if a ticket is raised about it; to answer one anyway, use its number)\n\n");
            foreach (var g in listed.GroupBy(LinkTitle, StringComparer.Ordinal))
            {
                sb.Append($"- `{g.Key}`\n");
                foreach (var e in g) sb.Append($"  - {ListedLine(e)}\n");
            }
            sb.Append('\n');
        }
        sb.Append(Caveat);
        return sb.ToString().TrimEnd('\n') + "\n";
    }

    const string Caveat = "Every finding comes from an AI reading the code. Code checked that each quoted spec sentence is real and that each code line exists, not that the AI understood the code correctly. If an answer looks wrong to you, say so: that's a useful answer too.\n";

    static string ModuleFile(Area area, Module m, Flows flows)
    {
        var doc = flows.Doc;
        var runs = (int)flows.Map["review"]!["runs"]!;
        var sb = new StringBuilder(Marker(doc)).Append("\n\n");
        sb.Append($"# {m.Title}\n\n");
        sb.Append($"[← {LinkText(area.Title)}](summary.md) · [index](../../../{IndexName}) · questions numbered for map `{PmAnswers.MapId(flows.Map)}`\n\n");
        if (m.Section is { } s)
        {
            var text = (string?)s["text"];
            if (text is null) sb.Append("_This section isn't in the spec any more; its answers are kept until you drop them._\n\n");
            else if (!string.IsNullOrWhiteSpace(text)) sb.Append(string.Join("\n", text.TrimEnd().Split('\n').Select(l => l.Length == 0 ? ">" : "> " + l))).Append("\n\n");
        }
        else sb.Append($"Code on `{m.Title}` that no section of the spec covers.\n\n");
        var c = Count(m);
        if (c.Questions == 0) sb.Append(c.Listed == 0 ? "**Nothing to answer.** The review found no difference here.\n\n" : "**Nothing to answer here.**\n\n");
        else sb.Append($"**Questions {Numbers(m)}**, {c.Open} still open. Answer by number: tell Claude (`/stangent:rule {doc}`), for example `21 fsd, 22 code, 23 yes, 24 keep \"what it should do\"`, or the rule in your own words.\n\n");

        if (m.Section is { } sec && (int?)sec["matches"]!["n"] is { } mn) Matches(sb, sec, mn, m.Entries.Where(IsMatch).ToList());
        foreach (var e in Questions(m)) Question(sb, e, runs, flows);

        var listed = m.Entries.Where(Listed).ToList();
        if (listed.Count > 0)
        {
            sb.Append("### Listed, no answer needed\n\nYou're asked about one only if a ticket is raised about it; to answer one anyway, use its number.\n\n");
            foreach (var e in listed) sb.Append($"- {ListedLine(e)}\n");
            sb.Append('\n');
        }
        Developers(sb, m, flows);
        return sb.ToString().TrimEnd('\n') + "\n";
    }

    static void Matches(StringBuilder sb, JsonObject section, int n, List<JsonObject> matches)
    {
        var open = OpenMatches(section);
        var m = section["matches"]!;
        sb.Append($"### {n}. Looks right: {(matches.Count == 1 ? "this sentence looks true of the app. Is it?" : "these sentences look true of the app. Are they?")}\n\n");
        foreach (var e in matches)
        {
            var conf = (string?)e["confidence"] is { } cf ? $" · {cf} confidence" : "";
            sb.Append($"- **{(int)e["n"]!}.** {TruthMap.Quote(e)} · {TruthMap.StandingWords(e)}{conf}{((bool)e["new"]! ? " · **new** since this section was confirmed" : "")}\n");
            if (e["writtenFrom"] is JsonObject w) sb.Append($"  - {TruthMap.Written(w, e)}\n");
        }
        sb.Append('\n');
        if (open) sb.Append(matches.Count == 1 ? "**Answer `yes`, or `no`.** " : "**Answer `yes` for all, or `no` on the number of the one that isn't.** ")
            .Append("A confirmed sentence lets a ticket that goes against it be turned away. Code checked the quotes and the lines, not that the app does what the sentences say.\n\n");
        else if ((bool)m["confirmed"]!) sb.Append($"Confirmed {TruthMap.By(m)}.\n\n");
    }

    static void Question(StringBuilder sb, JsonObject e, int runs, Flows flows)
    {
        var state = (string)e["state"]!;
        sb.Append($"### {(int)e["n"]!}. {KindLabel(state)}: {Headline(e)}\n\n");
        var quote = TruthMap.Quote(e);
        // One line each, so a note with a line break can't end the quote.
        var notes = e["notes"]!.AsArray().Select(x => Regex.Replace((string)x!, @"\s+", " ").Trim()).ToList();
        var lines = new List<string>();
        if (quote.Length > 0) lines.Add($"**Spec says:** {quote}");
        foreach (var note in notes) lines.Add($"**App does:** {note}");
        if (lines.Count > 0) sb.Append(string.Join("\n>\n", lines.Select(l => "> " + l))).Append("\n\n");
        sb.Append($"**Where it stands:** {TruthMap.StandingWords(e)}{((bool)e["new"]! ? " · **new** since its section was confirmed" : "")}\n\n");
        var link = e["link"]!;
        sb.Append($"**How sure:** {TruthMap.Found(e, runs)}{((bool)e["disagrees"]! ? " · the runs disagree: one called it a match" : "")} · linked to the {(string)link["kind"]!} `{LinkTitle(e)}`\n\n");
        if ((string?)e["statement"] is { } st) sb.Append($"**Your words:** {st}\n\n");
        if ((string?)e["pmNote"] is { } pm) sb.Append($"**Your note:** {pm}\n\n");
        if (e["writtenFrom"] is JsonObject w) sb.Append($"{TruthMap.Written(w, e)}\n\n");
        if ((string)link["kind"]! == "flow" && flows.Pick((string)link["id"]!) is { } p) HowItWorks(sb, p, flows.Words(p), flows.Doc);
        if (Open(e)) sb.Append(Answers(state, (bool?)e["needsWords"] == true)).Append("\n\n");
    }

    /// <summary>What each answer causes (D415 (3)).</summary>
    static string Answers(string state, bool needsWords) => state switch
    {
