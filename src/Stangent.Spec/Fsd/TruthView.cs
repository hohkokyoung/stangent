    /// <summary>The flow in plain words (D416): actor, journey, edge cases and a chart drawn by code from the same picks; a pick
    /// whose words failed the check shows the code's own label, marked. Without words: says so, and how to run the step.</summary>
    static void HowItWorks(StringBuilder sb, FlowWords.Picked p, FlowWords.Worded? w, string doc)
    {
        if (w is null)
        {
            sb.Append($"**How it works today:** {NotWorded(doc)} The code's steps are in the developer section below.\n\n");
            return;
        }
        string Line(FlowWords.Item i) => w.Lines.TryGetValue(i.Id, out var t) && !w.Failed.Contains(i.Id) ? t : $"`{Code(Cut(i.Code, 100))}` _(the code's own label: its plain words failed the check)_";
        sb.Append($"**How it works today** ({(w.Title.Length > 0 ? w.Title : p.Name)}; from the code's flow `{p.Flow}`, each line checked against one step, D416)\n\n");
        if (p.Items.FirstOrDefault(i => i.Kind == "actor") is { } actor) sb.Append($"- **Actor:** {Line(actor)}\n");
        var journey = p.Items.Where(i => i.Kind is "start" or "change").ToList();
        sb.Append("- **Journey:**\n");
        foreach (var (i, k) in journey.Select((i, k) => (i, k + 1))) sb.Append($"  {k}. {Line(i)}\n");
        if (p.MoreChanges > 0) sb.Append($"  - and {Plural(p.MoreChanges, "more change", "more changes")}, in the developer section\n");
        var stops = p.Items.Where(i => i.Kind == "stop").ToList();
        if (stops.Count > 0)
        {
            sb.Append("- **Edge cases:**\n");
            foreach (var i in stops) sb.Append($"  - {Line(i)}\n");
            if (p.MoreStops > 0) sb.Append($"  - and {Plural(p.MoreStops, "more way it stops", "more ways it stops")}, in the developer section\n");
        }
        sb.Append('\n');
        // The chart: the journey in order, each edge case as a dashed branch from the start (code draws it; no AI).
        sb.Append("```mermaid\nflowchart TD\n");
        string Box(FlowWords.Item i) => $"[\"{PageChart.Escape(Cut(Line(i), 80))}\"]";
        for (var k = 0; k < journey.Count; k++)
            sb.Append(k == 0 ? $"  {journey[k].Id}{Box(journey[k])}\n" : $"  {journey[k - 1].Id} --> {journey[k].Id}{Box(journey[k])}\n");
        var first = journey.Count > 0 ? journey[0].Id : null;
        foreach (var i in stops) sb.Append(first is null ? $"  {i.Id}{Box(i)}\n" : $"  {first} -.-> {i.Id}{Box(i)}\n");
        sb.Append("```\n\n");
    }

    static string NotWorded(string doc) =>
        $"_not in plain words yet (`plugin/scripts/fsd-view-run.sh --max-cost <usd> {doc}`, D416)._";

    static void Developers(StringBuilder sb, Module m, Flows flows)
    {
        if (m.Entries.Count == 0) return;
        sb.Append("<details><summary>For developers: where in the code</summary>\n\n");
        sb.Append("| # | Found | Code | Linked to |\n|---|---|---|---|\n");
        foreach (var e in m.Entries)
        {
            var link = e["link"]!;
            var ev = string.Join(", ", e["evidence"]!.AsArray().Select(v => $"`{(string)v!}`"));
            sb.Append($"| {(int)e["n"]!} | {(string)e["state"]!}{(Listed(e) ? ", listed" : "")} | {(ev.Length > 0 ? Cell(ev) : "no lines")} | {(string)link["kind"]!} `{Cell((string)link["id"]!)}` |\n");
        }
        sb.Append('\n');
        foreach (var id in LinkedFlows(Questions(m)))
        {
            if (flows.Pick(id) is not { } p) continue;
            var w = flows.Words(p);
            sb.Append($"Flow `{id}` (`{p.File}`), the steps its plain words were checked against:\n\n");
            foreach (var i in p.Items)
            {
                var said = w is null ? "" : w.Failed.Contains(i.Id) ? " · words failed the check" : w.Lines.TryGetValue(i.Id, out var t) ? $" · “{t}”" : "";
                var when = i.Conditions.Count > 0 ? $" — {string.Join("; ", i.Conditions.Select(Cell))}" : "";
                sb.Append($"- {i.Id} ({i.Kind}): `{Code(Cut(i.Code, 160))}`{when} (`{i.At}`){said}\n");
            }
            if (p.MoreChanges + p.MoreStops > 0) sb.Append($"- and {p.MoreChanges} more changes, {p.MoreStops} more stops, in `{p.File}`\n");
            sb.Append('\n');
        }
        sb.Append("</details>\n\n");
    }

