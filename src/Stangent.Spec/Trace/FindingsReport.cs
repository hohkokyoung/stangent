using System.Text;
using System.Text.Json.Nodes;
using Stangent.Core;

namespace Stangent.Spec.Trace;

/// <summary>
/// <c>stangent trace findings</c> (D152): the BA's queue as one readable Markdown file, by code with no AI. Grouped by how strong the evidence is,
/// strongest first, so a person reads what code backs before what it couldn't settle. Generated and read by nothing: <c>specs/trace.yaml</c>
/// stays the record, and a person still answers there. Writes only when asked, so it needs no switch.
/// </summary>
public static class FindingsReport
{
    /// <summary>The groups in reading order, each with the words a BA sees above it.</summary>
    public static readonly (string Key, string Title, string Hint)[] Groups =
    [
        ("code-shows", "The code shows the difference", "An AI read the code and quoted the line that differs; code checked the quote is there. Read the line, then say which side is right."),
        ("sent-back", "Sent back to you", "A developer read the AI's reason and didn't agree with it."),
        ("not-tested", "Not checked against the code", "Mostly screens or behaviour the FSD doesn't mention, which the code check can't test, or findings from before the check ran."),
        ("cant-tell", "The AI couldn't tell from the code it saw", "The weakest evidence: the code it was shown didn't settle it either way. Look at the code yourself before you rule."),
        ("other", "Other", "Findings of another kind, such as a table compared by code."),
    ];

    public static string DefaultPath(string doc) => $"specs/fsd/{doc}/findings.md";

    static readonly string[] Answers = [.. TraceFile.Decisions.Where(d => d != "agree")];

    public static string Group(JsonObject e)
    {
        if (TraceFindings.ReviewHolds(e) && (string?)e["review"] == "sent-back") return "sent-back";
        if (e["table_fact"] is not null) return "other";
        return (string?)e["verdict"] switch
        {
            "stands" => "code-shows",
            "cant-tell" => "cant-tell",
            null => "not-tested",
            _ => "other",
        };
    }

    public static JsonObject Run(string root, string doc, string? outPath)
    {
        var path = outPath ?? DefaultPath(doc);
        var full = Path.GetFullPath(Path.Combine(root, path));
        var index = SpecIndex.Load(root);
        var entries = TraceFile.Sorted(TraceFile.Load(root)["entries"]!.AsArray())
            .Where(e => e["fsd"] is null || (string?)e["fsd"]!["doc"] == doc).Where(e => TraceFindings.IsFinding(e) && !TraceFindings.IsGone(e)).ToList();
        var mine = entries.Where(e => TraceFindings.GoesTo(e) == "ba").ToList();
        var withDeveloper = entries.Count(e => TraceFindings.GoesTo(e) is "developer" or "developer-confirm");
        var byGroup = Groups.ToDictionary(g => g.Key, g => mine.Where(e => Group(e) == g.Key).ToList());

        var sb = new StringBuilder();
        sb.Append($"<!-- Generated by `stangent trace findings {doc}`. Nothing reads this file: answer in specs/trace.yaml, then run the command again. -->\n\n");
        sb.Append($"# Findings waiting for you: {doc}\n\n");
        sb.Append($"{mine.Count} finding(s) where the FSD and the code seem to disagree, strongest evidence first. For each, say which side is right.");
        if (withDeveloper > 0) sb.Append($" {withDeveloper} more are with a developer, who checks what the AI said is no difference, and aren't listed here.");
        sb.Append("\n\n| Group | Findings |\n|---|---|\n");
        foreach (var (key, title, _) in Groups.Where(g => byGroup[g.Key].Count > 0)) sb.Append($"| {title} | {byGroup[key].Count} |\n");
        sb.Append($"\n**How to answer:** in `specs/trace.yaml`, find the entry id shown and set `decision:` to one of {string.Join(", ", Answers.Select(a => $"`{a}`"))}, in a PR. `code-wrong` means the code should change, `fsd-wrong` the document, `page-wrong` the page; `accepted` keeps the difference as it is.\n");

        foreach (var (key, title, hint) in Groups.Where(g => byGroup[g.Key].Count > 0))
        {
            sb.Append($"\n## {title} ({byGroup[key].Count})\n\n{hint}\n");
            foreach (var e in byGroup[key]) Block(sb, e, index);
        }

        var text = sb.ToString();
        var written = !File.Exists(full) || File.ReadAllText(full) != text;
        if (written)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(full)!);
            File.WriteAllText(full, text);
        }
        return new JsonObject
        {
            ["doc"] = doc, ["path"] = Path.GetRelativePath(root, full).Replace('\\', '/'), ["written"] = written,
            ["findings"] = mine.Count, ["withDeveloper"] = withDeveloper,
            ["groups"] = new JsonObject(Groups.Select(g => KeyValuePair.Create(g.Key, (JsonNode?)byGroup[g.Key].Count))),
        };
    }

    static void Block(StringBuilder sb, JsonObject e, SpecIndex index)
    {
        var state = (string)e["state"]!;
        var section = (string?)e["fsd"]?["section"];
        var title = (string?)e["fsd"]?["title"];
        sb.Append($"\n### {(string?)e["finding"] ?? (string)e["id"]!} · {state}{(section is null ? "" : $" · §{section}{(title is null ? "" : $" {title}")}")}\n\n");

        var fsdQuote = (string?)e["fsd"]?["quote"];
        sb.Append(fsdQuote is null ? "- **The FSD says:** nothing about this.\n" : $"- **The FSD says:** \"{fsdQuote}\"\n");
        var pageId = (string?)e["page"]?["id"];
        var statement = (string?)e["page"]?["statement"];
        sb.Append(pageId is null ? "- **What the code does:** no page describes it.\n"
            : statement is null ? $"- **What the code does:** no statement on `{pageId}` says this.\n"
            : $"- **What the code does** (`{pageId}`, {statement}): \"{(string?)e["page"]?["quote"]}\"\n");

        if ((string?)e["disproof"]?["path"] is { } path)
        {
            var (start, end) = ((int)e["disproof"]!["start"]!, (int)e["disproof"]!["end"]!);
            sb.Append($"- **The code line:** `{path}:{start}{(end != start ? $"-{end}" : "")}`\n\n  ```\n  {((string?)e["disproof"]!["quote"] ?? "").Replace("\n", "\n  ")}\n  ```\n\n");
        }
        else if (TraceLinks.Link(e, index)["code"]!.AsArray().OfType<JsonObject>().Take(3).ToList() is { Count: > 0 } lines)
            sb.Append($"- **Where to look** (the page's citations, not checked against the FSD): {string.Join(", ", lines.Select(l => $"`{(string)l["path"]!}:{l["lines"]}`"))}\n");

        if ((string?)e["disproof"]?["why"] is { } why) sb.Append($"- **The AI's reading:** {why}\n");
        else if ((string?)e["note"] is { } note) sb.Append($"- **The link judge's note:** {note}\n");
        if (TraceFindings.ReviewHolds(e) && (string?)e["review"] == "sent-back") sb.Append($"- **Sent back by {(string?)e["review_note"]?["by"]}:** {(string?)e["review_note"]?["why"]}\n");
        if ((string?)e["disproof"]?["suggestedSeverity"] is { } severity) sb.Append($"- **Suggested severity:** {severity} (the AI's suggestion; a person sets it)\n");
        if (TraceFindings.SecurityOpen(e)) sb.Append("- **Security flag:** unanswered; a developer answers it with `stangent trace security`.\n");
        sb.Append($"- **Your answer:** entry `{(string)e["id"]!}` in `specs/trace.yaml`, `decision:`\n");
    }
}
