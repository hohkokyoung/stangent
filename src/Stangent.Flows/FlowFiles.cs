using System.Text;
using System.Text.Json.Nodes;
using Stangent.Core;
using Stangent.Graph;

namespace Stangent.Flows;

/// <summary>
/// Flows on disk (D180): <c>specs/flows/&lt;id&gt;.json</c> (contract <c>flows</c> v1), <c>&lt;id&gt;.md</c> (the template sentences,
/// generated, never read back) and <c>index.json</c>. Canonical JSON and fixed text, so the same graph writes the same bytes (D176).
/// </summary>
public static class FlowFiles
{
    public const string Contract = "flows";
    public const int Version = 1;
    public const string Folder = "specs/flows";
    const string Marker = "<!-- generated by `stangent flows build` (D180): do not edit; rebuild instead -->";

    /// <summary>Every file the set writes, by its path under the repo, with its exact text.</summary>
    public static SortedDictionary<string, string> Render(FlowSet set)
    {
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var f in set.Flows)
        {
            files[$"{Folder}/{f.Id}.json"] = CanonicalJson.Serialize(Json(f, set));
            files[$"{Folder}/{f.Id}.md"] = Markdown(f, set);
        }
        files[$"{Folder}/index.json"] = CanonicalJson.Serialize(Index(set));
        return files;
    }

    /// <summary>Writes the set and removes flow files no longer in it. Returns what changed.</summary>
    public static (int Written, int Removed, int Unchanged) Write(string root, FlowSet set)
    {
        var files = Render(set);
        var dir = Path.Combine(root, Folder);
        Directory.CreateDirectory(dir);
        int written = 0, removed = 0, same = 0;
        foreach (var (rel, text) in files)
        {
            var path = Path.Combine(root, rel);
            if (File.Exists(path) && File.ReadAllText(path) == text) { same++; continue; }
            File.WriteAllText(path, text, new UTF8Encoding(false));
            written++;
        }
        foreach (var path in Directory.EnumerateFiles(dir).Where(p => p.EndsWith(".json", StringComparison.Ordinal) || p.EndsWith(".md", StringComparison.Ordinal)).Order(StringComparer.Ordinal))
            if (!files.ContainsKey($"{Folder}/{Path.GetFileName(path)}")) { File.Delete(path); removed++; }
        return (written, removed, same);
    }

    static JsonObject Settings(FlowSet set) => new() { ["hubCallers"] = set.Settings.HubCallers, ["depth"] = set.Settings.Depth };

    static void PutAt(JsonObject o, At? at)
    {
        if (at is null) return;
        o["at"] = at.ToString();
        o["code"] = at.Code;
    }

    /// <summary>How a condition's quoted code reads after "only if": D215 `cache-miss`, D216 `set`.</summary>
    static string Reading(string kind) => kind switch
    {
        "else" => " is false",
        "unless" => " is false (an earlier guard)",
        "cache-miss" => " finds nothing stored for the key",
        "set" => " is set",
        _ => "",
    };

    static JsonArray Conditions(IEnumerable<Condition> cs) => [.. cs.Select(c =>
    {
        var o = new JsonObject { ["kind"] = c.Kind, ["at"] = $"{c.File}:{c.Line}", ["code"] = c.Code };
        if (c.Case is not null) o["case"] = c.Case;
        return (JsonNode)o;
    })];

    public static JsonObject Json(Flow f, FlowSet set)
    {
        var start = new JsonObject { ["what"] = f.Start.What, ["point"] = f.Start.Point, ["triggers"] = new JsonArray([.. f.Start.Triggers.Select(t => (JsonNode)t)]) };
        PutAt(start, f.Start.At);
        var actor = new JsonObject { ["who"] = f.Actor.Who, ["why"] = f.Actor.Why, ["label"] = f.Actor.Guessed ? "guessed" : "certain" };
        PutAt(actor, f.Actor.At);
        return new JsonObject
        {
            ["contract"] = Contract, ["version"] = Version, ["commit"] = set.Commit, ["settings"] = Settings(set),
            ["id"] = f.Id, ["name"] = f.Name, ["kind"] = f.Kind, ["home"] = f.Home, ["start"] = start, ["actor"] = actor,
            ["inputs"] = new JsonArray([.. f.Inputs.Select(i => (JsonNode)i)]),
            ["checks"] = new JsonArray([.. f.Checks.Select(c =>
            {
                var o = new JsonObject { ["what"] = c.What, ["rule"] = c.Rule, ["property"] = c.Property, ["message"] = c.Message, ["onlyWarns"] = c.OnlyWarns };
                PutAt(o, c.At);
                return (JsonNode)o;
            })]),
            ["steps"] = new JsonArray([.. f.Steps.Select(st =>
            {
                var o = new JsonObject { ["n"] = st.N, ["kind"] = st.Kind, ["what"] = st.What, ["label"] = st.Guessed ? "guessed" : "certain", ["conditions"] = Conditions(st.Conditions) };
                if (st.From is not null) o["from"] = st.From;
                PutAt(o, st.At);
                if (st.Point is not null) o["point"] = st.Point;
                if (st.GuessReason is not null) o["reason"] = st.GuessReason;
                if (st.End is not null) o["end"] = new JsonObject { ["kind"] = st.End.Kind, ["detail"] = st.End.Detail };
                if (st.BackTo is not null) o["backTo"] = st.BackTo;
                if (st.SameAs is not null) o["sameAs"] = st.SameAs;
                if (st.Runs is not null) o["runs"] = st.Runs;
                return (JsonNode)o;
            })]),
            ["exits"] = new JsonArray([.. f.Exits.Select(e =>
            {
                var o = new JsonObject { ["kind"] = e.Kind, ["what"] = e.What, ["point"] = e.Point, ["conditions"] = Conditions(e.Conditions) };
                if (e.Step is not null) o["step"] = e.Step;
                PutAt(o, e.At);
                return (JsonNode)o;
            })]),
            ["scenarios"] = new JsonArray([.. f.Scenarios.Select(sc =>
            {
                var o = new JsonObject { ["name"] = sc.Name, ["conditions"] = Conditions(sc.Conditions) };
                if (sc.Exit is not null) o["exit"] = sc.Exit;
                return (JsonNode)o;
            })]),
            ["links"] = new JsonArray([.. f.Links.Select(l =>
            {
                var o = new JsonObject { ["kind"] = l.Kind, ["to"] = l.To, ["sentence"] = l.Sentence, ["label"] = l.Guessed ? "guessed" : "certain" };
                if (l.ToFlow is not null) o["flow"] = l.ToFlow;
                if (l.Step is not null) o["step"] = l.Step;
                PutAt(o, l.At);
                return (JsonNode)o;
            })]),
            ["guesses"] = new JsonArray([.. f.Guesses.Select(x =>
            {
                var o = new JsonObject { ["what"] = x.What, ["reason"] = x.Reason };
                if (x.Step is not null) o["step"] = x.Step;
                return (JsonNode)o;
            })]),
            ["unknowns"] = new JsonArray([.. f.Unknowns.Select(u =>
            {
                var o = new JsonObject { ["point"] = u.Point, ["why"] = u.Why };
                if (u.Step is not null) o["step"] = u.Step;
                PutAt(o, u.At);
                return (JsonNode)o;
            })]),
            ["displayOnly"] = new JsonArray([.. f.DisplayOnly.Select(d => (JsonNode)d)]),
        };
    }

    public static JsonObject Index(FlowSet set) => new()
    {
        ["contract"] = Contract, ["version"] = Version, ["commit"] = set.Commit, ["settings"] = Settings(set),
        ["flows"] = new JsonArray([.. set.Flows.Select(f => (JsonNode)new JsonObject
        {
            ["id"] = f.Id, ["name"] = f.Name, ["kind"] = f.Kind, ["home"] = f.Home, ["start"] = f.Start.At.ToString(), ["point"] = f.Start.Point,
            ["steps"] = f.Steps.Count, ["guesses"] = f.Guesses.Count, ["unknowns"] = f.Unknowns.Count,
            ["links"] = new JsonArray([.. f.Links.Where(l => l.ToFlow is not null).Select(l => l.ToFlow!).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).Select(x => (JsonNode)x)]),
        })]),
        ["skipped"] = new JsonArray([.. set.Skipped.Select(s => (JsonNode)new JsonObject
        {
            ["kind"] = s.Kind, ["point"] = s.Point, ["at"] = s.At.ToString(), ["code"] = s.At.Code, ["reason"] = s.Reason,
        })]),
    };

    /// <summary>The flow as fixed sentences filled in by code (D173): what layer 4 may reword later, checked.</summary>
    public static string Markdown(Flow f, FlowSet set)
    {
        var sb = new StringBuilder();
        sb.Append(Marker).Append('\n').Append('\n');
        sb.Append($"# {f.Name}\n\n");
        sb.Append($"- **Kind:** {f.Kind}\n- **Starts:** {f.Start.What}, at `{f.Start.At}`\n");
        sb.Append($"- **Who:** {f.Actor.Who}{(f.Actor.Guessed ? " 🟡" : "")} ({f.Actor.Why}{(f.Actor.At is { } a ? $", `{a}`" : "")})\n");
        sb.Append($"- **Built from:** commit `{set.Commit}`, hubs at {set.Settings.HubCallers} callers, {set.Settings.Depth} calls deep\n");
        if (f.Start.Triggers.Count > 0) sb.Append($"- **Run by:** {string.Join("; ", f.Start.Triggers)}\n");
        if (f.Inputs.Count > 0) sb.Append($"- **Inputs:** {string.Join(", ", f.Inputs)}\n");
        if (f.Guesses.Count > 0)
        {
            sb.Append("\n## Guesses\n\n");
            foreach (var x in f.Guesses) sb.Append($"- 🟡 {(x.Step is { } n ? $"step {n}: " : "")}{x.What}: {x.Reason}\n");
        }
        if (f.Unknowns.Count > 0)
        {
            sb.Append("\n## Can't be followed\n\n");
            foreach (var u in f.Unknowns) sb.Append($"- ❓ {(u.Step is { } n ? $"step {n}: " : "")}{u.Why} (`{u.At}`)\n");
        }
        if (f.Checks.Count > 0)
        {
            sb.Append("\n## Checks\n\n");
            foreach (var c in f.Checks) sb.Append($"- {c.What}{(c.OnlyWarns ? " (only warns)" : "")}{(c.Message != "" ? $": \"{c.Message}\"" : "")} (`{c.At}`)\n");
        }
        sb.Append("\n## Steps\n\n");
        var depth = new Dictionary<int, int>();
        foreach (var st in f.Steps)
        {
            var d = st.From is { } p && depth.TryGetValue(p, out var pd) ? pd + 1 : 0;
            depth[st.N] = d;
            sb.Append(new string(' ', d * 2)).Append($"- {st.N}. {st.What}{(st.Guessed ? " 🟡" : "")}");
            if (st.Conditions.Count > 0) sb.Append($", only if `{st.Conditions[0].Code}`{Reading(st.Conditions[0].Kind)}");
            if (st.End is { } e) sb.Append($" — ends: {e.Kind}, {e.Detail}");
            if (st.BackTo is { } b) sb.Append(b == 0 ? " — goes back to the start" : $" — goes back to step {b}");
            if (st.SameAs is { } sa) sb.Append($" — as in step {sa}");
            sb.Append($" (`{st.At}`)\n");
        }
        if (f.Exits.Count > 0)
        {
            sb.Append("\n## Early exits\n\n");
            foreach (var e in f.Exits) sb.Append($"- {e.What}{(e.Conditions.Count > 0 ? $", only if `{e.Conditions[0].Code}`" : "")}{(e.Step is { } n ? $", in step {n}" : "")} (`{e.At}`)\n");
        }
        sb.Append("\n## Scenarios\n\n");
        foreach (var sc in f.Scenarios) sb.Append($"- {sc.Name}{(sc.Conditions.Count > 0 ? $": {string.Join(" ← ", sc.Conditions.Select(c => $"`{c.Code}`"))}" : "")}\n");
        if (f.Links.Count > 0)
        {
            sb.Append("\n## Links\n\n");
            foreach (var l in f.Links) sb.Append($"- {l.Sentence}{(l.ToFlow is not null ? $" → `{l.ToFlow}`" : "")}\n");
        }
        if (f.DisplayOnly.Count > 0) sb.Append($"\n**Display only, not walked into:** {string.Join(", ", f.DisplayOnly)}\n");
        return sb.ToString();
    }

    // ---- flows check: D177 bar items 3–5 by code ---------------------------------------------------------------------

    /// <summary>
    /// Items 3–5 of D177's bar: every 🟡 has a reason and every ❓ says why; the files on disk are byte for byte what this graph
    /// builds; every start code finds is a flow or a stated reason. Problems, empty when it passes.
    /// </summary>
    public static JsonObject Check(string root, CodeGraph graph, FlowSettings settings)
    {
        var set = FlowBuilder.Build(graph, root, settings);
        var want = Render(set);
        var problems = new List<string>();
        var dir = Path.Combine(root, Folder);
        var onDisk = Directory.Exists(dir)
            ? Directory.EnumerateFiles(dir).Where(p => p.EndsWith(".json", StringComparison.Ordinal) || p.EndsWith(".md", StringComparison.Ordinal))
                .Select(p => $"{Folder}/{Path.GetFileName(p)}").Order(StringComparer.Ordinal).ToList()
            : [];
        var differ = want.Where(kv => !File.Exists(Path.Combine(root, kv.Key)) || File.ReadAllText(Path.Combine(root, kv.Key)) != kv.Value).Select(kv => kv.Key).ToList();
        var extra = onDisk.Where(p => !want.ContainsKey(p)).ToList();
        problems.AddRange(differ.Select(p => $"byte-for-byte: {p} isn't what this graph builds (run `stangent flows build`)"));
        problems.AddRange(extra.Select(p => $"byte-for-byte: {p} is no longer a flow"));
        foreach (var f in set.Flows)
        {
            problems.AddRange(f.Guesses.Where(x => string.IsNullOrWhiteSpace(x.Reason)).Select(x => $"reasons: {f.Id}: a 🟡 with no reason ({x.What})"));
            problems.AddRange(f.Steps.Where(st => st.Guessed && string.IsNullOrWhiteSpace(st.GuessReason)).Select(st => $"reasons: {f.Id}: step {st.N} is 🟡 with no reason"));
            problems.AddRange(f.Unknowns.Where(u => string.IsNullOrWhiteSpace(u.Why)).Select(u => $"reasons: {f.Id}: a ❓ that doesn't say why ({u.At})"));
        }
        var starts = Starts(graph);
        var covered = set.Flows.Select(f => f.Start.Point).Concat(set.Flows.SelectMany(f => f.Reached)).Concat(set.Skipped.Select(x => x.Point)).ToHashSet(StringComparer.Ordinal);
        var silent = starts.Where(st => !covered.Contains(st.Point)).ToList();
        problems.AddRange(silent.Select(st => $"silent skip: {st.Kind} {st.Point} ({st.At}) is neither a flow nor a stated reason"));
        return new JsonObject
        {
            ["ok"] = problems.Count == 0,
            ["flows"] = set.Flows.Count, ["skipped"] = set.Skipped.Count, ["starts"] = starts.Count,
            ["guesses"] = set.Flows.Sum(f => f.Guesses.Count), ["unknowns"] = set.Flows.Sum(f => f.Unknowns.Count),
            ["problems"] = new JsonArray([.. problems.Order(StringComparer.Ordinal).Select(p => (JsonNode)p)]),
        };
    }

    /// <summary>Every start in the graph, found apart from the builder (D171): each click's handler, page, page load, job, handler.</summary>
    static List<(string Kind, string Point, string At)> Starts(CodeGraph graph)
    {
        var tests = graph.AllNodes.Where(n => n.IsTest).Select(n => n.Id).ToHashSet(StringComparer.Ordinal);
        var ids = graph.AllNodes.Select(n => n.Id).ToHashSet(StringComparer.Ordinal);
        var list = new List<(string, string, string)>();
        foreach (var f in graph.AllFacts.Where(f => !tests.Contains(f.Owner)))
            switch (f.Kind)
            {
                case "ui-event":
                    var h = f["handler"];
                    list.Add(("click", h == "" || h == "inline" || h.StartsWith("prop:", StringComparison.Ordinal) || !ids.Contains(h) ? f.Owner : h, $"{f.File}:{f.Line}"));
                    break;
                case "on-load": list.Add(("screen-opens", f.Owner, $"{f.File}:{f.Line}")); break;
                case "is-job": list.Add(("job", f.Owner, $"{f.File}:{f.Line}")); break;
            }
        foreach (var n in graph.AllNodes.Where(n => n.Kind == NodeKind.Page && !n.IsTest)) list.Add(("screen-opens", n.Id, $"{n.File}:{n.Line}"));
        return [.. list.Distinct()];
    }
