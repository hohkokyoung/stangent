using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;
using Stangent.Core;
using Stangent.Graph;

namespace Stangent.Flows;

/// <summary>
/// The inventory on disk (D329, D334): <c>specs/inventory.json</c> (contract <c>inventory</c> v1) and <c>specs/inventory.md</c> (generated,
/// never read back). Canonical JSON and fixed text, so the same graph writes the same bytes; <see cref="Check"/> is D334 item 7.
/// </summary>
public static class InventoryFiles
{
    public const string Contract = "inventory";
    public const int Version = 2;
    /// <summary>D362 (3)'s group name.</summary>
    public const string AppFrameTitle = "App frame (on every screen)";
    public const string JsonFile = "specs/inventory.json";
    public const string MarkdownFile = "specs/inventory.md";
    const string Marker = "<!-- generated by `stangent inventory` (D334): do not edit; rebuild instead -->";

    static readonly string[] Kinds = ["button", "menu-entry", "field", "server-field"];

    /// <summary>Both files by their path under the repo, with their exact text.</summary>
    public static SortedDictionary<string, string> Render(InventorySet set) => new(StringComparer.Ordinal)
    {
        [JsonFile] = CanonicalJson.Serialize(Json(set)),
        [MarkdownFile] = Markdown(set),
    };

    /// <summary>Writes the files that changed. Returns how many were written and left as they were.</summary>
    public static (int Written, int Unchanged) Write(string root, InventorySet set)
    {
        int written = 0, same = 0;
        foreach (var (rel, text) in Render(set))
        {
            var path = Path.Combine(root, rel);
            if (File.Exists(path) && File.ReadAllText(path) == text) { same++; continue; }
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, text, new UTF8Encoding(false));
            written++;
        }
        return (written, same);
    }

    // ---- counts -------------------------------------------------------------------------------------------------------------

    /// <summary>D334 item 6's counts: screens, lines by kind, share named by visible text, ❓, skipped by reason, set aside, Not placed.</summary>
    public static JsonObject Counts(InventorySet set)
    {
        var lines = set.AllLines.ToList();
        var named = lines.Count(l => l.Name.Visible);
        var notPlaced = set.NotPlaced;
        return new JsonObject
        {
            ["screens"] = set.Screens.Count,
            ["lines"] = new JsonObject([KeyValuePair.Create("total", (JsonNode?)lines.Count), .. Kinds.Select(k => KeyValuePair.Create(k, (JsonNode?)lines.Count(l => l.Kind == k)))]),
            ["named"] = named, ["namedShare"] = Share(named, lines.Count), ["unnamed"] = lines.Count - named,
            ["skipped"] = new JsonObject([KeyValuePair.Create("total", (JsonNode?)set.Skipped.Count),
                .. Inventory.SkipReasons.Select(r => KeyValuePair.Create(r, (JsonNode?)set.Skipped.Count(s => s.Reason == r)))]),
            ["setAside"] = new JsonObject([KeyValuePair.Create("total", (JsonNode?)set.SetAside.Count),
                .. set.SetAside.GroupBy(s => s.Reason).OrderBy(x => x.Key, StringComparer.Ordinal).Select(x => KeyValuePair.Create(x.Key, (JsonNode?)x.Count()))]),
            ["sharedParts"] = new JsonObject { ["groups"] = set.Shared.Count, ["lines"] = set.Shared.Sum(g => g.Lines.Count) },
            ["appFrame"] = new JsonObject { ["roots"] = set.Roots.Count, ["groups"] = set.AppFrame.Count, ["lines"] = set.AppFrame.Sum(g => g.Lines.Count) },
            ["notPlaced"] = new JsonObject
            {
                ["groups"] = notPlaced.Count, ["lines"] = notPlaced.Sum(g => g.Lines.Count),
                ["serverClasses"] = notPlaced.Count(g => g.Kind == "server-class"),
                ["parts"] = notPlaced.Count(g => g.Kind is "part" or "dialog"), ["menus"] = notPlaced.Count(g => g.Kind == "menu"),
            },
            ["dialogs"] = set.Dialogs,
            ["menus"] = new JsonObject { ["found"] = set.Menus, ["placed"] = set.MenusPlaced, ["notPlaced"] = set.Menus - set.MenusPlaced },
        };
    }

    static double Share(int n, int total) => total == 0 ? 0 : Math.Round(100.0 * n / total, 1);

    // ---- JSON ---------------------------------------------------------------------------------------------------------------

    public static JsonObject Json(InventorySet set) => new()
    {
        ["contract"] = Contract, ["version"] = Version, ["commit"] = set.Commit,
        ["counts"] = Counts(set),
        ["screens"] = new JsonArray([.. set.Screens.Select(s => (JsonNode)new JsonObject
        {
            ["id"] = s.Id, ["title"] = s.Line, ["named"] = s.Title.Visible,
            ["lines"] = Lines(s.Lines),
            ["dialogs"] = new JsonArray([.. s.Dialogs.Select(d => (JsonNode)Group(d))]),
            ["menus"] = new JsonArray([.. s.Menus.Select(m => (JsonNode)Group(m))]),
            ["pointers"] = new JsonArray([.. s.Pointers.Select(p => (JsonNode)new JsonObject { ["id"] = p.Id, ["text"] = Pointer(p) })]),
        })]),
        ["sharedParts"] = new JsonArray([.. set.Shared.Select(g => (JsonNode)Group(g, appearsOn: true))]),
        ["appFrame"] = new JsonObject
        {
            ["title"] = AppFrameTitle, ["roots"] = new JsonArray([.. set.Roots.Select(r => (JsonNode)r)]),
            ["groups"] = new JsonArray([.. set.AppFrame.Select(g => (JsonNode)Group(g))]),
        },
        ["notPlaced"] = new JsonArray([.. set.NotPlaced.Select(g => (JsonNode)Group(g))]),
        ["skipped"] = new JsonArray([.. set.Skipped.Select(s => { var o = Line(s.Line); o["reason"] = s.Reason; return (JsonNode)o; })]),
        ["setAside"] = new JsonArray([.. set.SetAside.Select(s => (JsonNode)new JsonObject
        {
            ["at"] = s.At, ["code"] = s.Name.Code, ["name"] = s.Name.Line, ["named"] = s.Name.Visible, ["reason"] = s.Reason,
            ["class"] = s.Fact["to"], ["attribute"] = s.Fact["attribute"],
        })]),
    };

    static string Pointer(InventoryGroup g) => $"uses {g.Title} ({g.Size()})";

    static JsonObject Group(InventoryGroup g, bool appearsOn = false)
    {
        var o = new JsonObject { ["id"] = g.Id, ["kind"] = g.Kind, ["title"] = g.Title, ["titleFromCode"] = g.TitleFromCode, ["size"] = g.Size(), ["lines"] = Lines(g.Lines) };
        if (appearsOn) o["appearsOn"] = new JsonArray([.. g.Screens.Select(s => (JsonNode)s)]);
        return o;
    }

    static JsonArray Lines(IEnumerable<InventoryLine> lines) => [.. lines.Select(l => (JsonNode)Line(l))];

    static JsonObject Line(InventoryLine l)
    {
        var o = new JsonObject { ["kind"] = l.Kind, ["name"] = l.Name.Line, ["named"] = l.Name.Visible, ["at"] = l.At, ["code"] = l.Code, ["part"] = l.Part };
        if (l.Name.Visible) o["source"] = l.Name.Source;
        else o["why"] = l.Name.Why;
        if (l.Name.Help is { } help) o["help"] = help;
        if (l.Handler != "") o["handler"] = l.Handler;
        if (l.Choices.Names.Count > 0) o["choices"] = new JsonArray([.. l.Choices.Names.Select(n => (JsonNode)n.Line)]);
        else if (l.Choices.Note != "") o["choices"] = l.Choices.Note;
        if (l.Merged.Count > 0) o["merged"] = new JsonArray([.. l.Merged.Select(f => (JsonNode)$"{f.File}:{f.Line}")]);
        return o;
    }

    // ---- Markdown -----------------------------------------------------------------------------------------------------------

    public static string Markdown(InventorySet set)
    {
        var c = Counts(set);
        var sb = new StringBuilder();
        sb.Append("# Inventory\n\n").Append(Marker).Append("\n\n");
        sb.Append($"Commit `{set.Commit}`. Every control a user can touch, named by the words they see (D325–D328, D334).\n\n");
        sb.Append(Header(c)).Append('\n');
        foreach (var s in set.Screens)
        {
            sb.Append($"## {s.Line}\n\n");
            if (s.Lines.Count == 0 && s.Pointers.Count == 0 && s.Dialogs.Count == 0 && s.Menus.Count == 0) sb.Append("No lines of its own.\n\n");
            AppendLines(sb, s.Lines);
            foreach (var p in s.Pointers) sb.Append($"- {Pointer(p)}: see Shared parts\n");
            if (s.Pointers.Count > 0 || s.Lines.Count > 0) sb.Append('\n');
            foreach (var d in s.Dialogs) AppendGroup(sb, "Dialog: ", d);
            foreach (var m in s.Menus) AppendGroup(sb, "Menu: ", m);
        }
        sb.Append("## Shared parts\n\n");
        if (set.Shared.Count == 0) sb.Append("None.\n\n");
        foreach (var g in set.Shared)
        {
            sb.Append($"### {Kind(g)}{Title(g)}\n\n");
            var on = g.Screens.Select(id => set.Screens.First(s => s.Id == id).Line);
            sb.Append($"Appears on {g.Screens.Count} screens: {string.Join("; ", on)}.\n\n");
            AppendLines(sb, g.Lines);
            sb.Append('\n');
        }
        sb.Append($"## {AppFrameTitle}\n\n");
        if (set.AppFrame.Count == 0) sb.Append(set.Roots.Count == 0 ? "No root component found.\n\n" : "Nothing the root draws or opens is left unplaced.\n\n");
        foreach (var g in set.AppFrame)
        {
            sb.Append($"### {Kind(g)}{Title(g)}\n\n");
            AppendLines(sb, g.Lines);
            sb.Append('\n');
        }
        sb.Append("## Not placed\n\n");
        if (set.NotPlaced.Count == 0) sb.Append("None.\n\n");
        foreach (var g in set.NotPlaced)
        {
            sb.Append(g.Kind == "server-class" ? $"### {g.Title}, {g.Size()} _(code name; drawn by a generic form from the server's list)_\n\n" : $"### {Kind(g)}{Title(g)}\n\n");
            AppendLines(sb, g.Lines);
            sb.Append('\n');
        }
        return sb.ToString().TrimEnd('\n') + "\n";
    }

    /// <summary>The counts block at the top of the <c>.md</c>.</summary>
    public static string Header(JsonObject c)
    {
        var sb = new StringBuilder();
        var lines = c["lines"]!.AsObject();
        sb.Append($"- Screens: {(int)c["screens"]!}\n");
        sb.Append($"- Lines: {(int)lines["total"]!} ({string.Join(", ", Kinds.Select(k => $"{k} {(int)lines[k]!}"))})\n");
        sb.Append($"- Named by visible text: {((double)c["namedShare"]!).ToString("0.0", CultureInfo.InvariantCulture)}% ({(int)c["named"]!} of {(int)lines["total"]!})\n");
        sb.Append($"- ❓: {(int)c["unnamed"]!}\n");
        var skipped = c["skipped"]!.AsObject();
        sb.Append($"- Skipped: {(int)skipped["total"]!} ({string.Join(", ", Inventory.SkipReasons.Select(r => $"{r} {(int)skipped[r]!}"))})\n");
        var aside = c["setAside"]!.AsObject();
        sb.Append($"- Set aside: {(int)aside["total"]!}{(aside.Count > 1 ? $" ({string.Join(", ", aside.Where(x => x.Key != "total").Select(x => $"{x.Key} {(int)x.Value!}"))})" : "")}\n");
        var shared = c["sharedParts"]!.AsObject();
        sb.Append($"- Shared parts: {(int)shared["groups"]!} ({(int)shared["lines"]!} lines)\n");
        if (c["appFrame"] is JsonObject frame) sb.Append($"- {AppFrameTitle}: {(int)frame["groups"]!} groups, {(int)frame["lines"]!} lines ({(int)frame["roots"]!} root{((int)frame["roots"]! == 1 ? "" : "s")})\n");
        var np = c["notPlaced"]!.AsObject();
        sb.Append($"- Not placed: {(int)np["groups"]!} groups, {(int)np["lines"]!} lines ({(int)np["parts"]!} parts, {(int)np["menus"]!} menus, {(int)np["serverClasses"]!} server classes)\n");
        var menus = c["menus"]!.AsObject();
        sb.Append($"- Dialogs found: {(int)c["dialogs"]!}; data menus: {(int)menus["found"]!} ({(int)menus["placed"]!} placed)\n");
        return sb.ToString();
    }

    static string Kind(InventoryGroup g) => g.Kind switch { "dialog" => "Dialog: ", "menu" => "Menu: ", _ => "" };
    static string Title(InventoryGroup g) => g.TitleFromCode ? $"{g.Title} _(code name)_" : g.Title;

    static void AppendGroup(StringBuilder sb, string prefix, InventoryGroup g)
    {
        sb.Append($"### {prefix}{Title(g)}\n\n");
        if (g.Lines.Count == 0) sb.Append("No lines of its own.\n");
        AppendLines(sb, g.Lines);
        sb.Append('\n');
    }

    static void AppendLines(StringBuilder sb, IEnumerable<InventoryLine> lines)
    {
        foreach (var l in lines)
        {
            sb.Append("- ").Append(KindLabel(l.Kind)).Append(": ").Append(l.Name.Visible ? $"**{l.Name.Words}**" : l.Name.Line);
            if (l.Name.Help is { } help) sb.Append($" (help: {help})");
            if (l.Choices.Names.Count > 0) sb.Append($"; choices: {string.Join(", ", l.Choices.Names.Select(n => n.Line))}");
            else if (l.Choices.Note != "") sb.Append($"; choices: {l.Choices.Note}");
            sb.Append($" · `{l.At}`");
            if (l.Name.Visible) sb.Append($" `{l.Code}`");
            sb.Append('\n');
        }
    }

    static string KindLabel(string kind) => kind switch { "button" => "Button", "menu-entry" => "Menu entry", "field" => "Field", _ => "Server field" };

    // ---- inventory check: D334 item 7 ---------------------------------------------------------------------------------------

    /// <summary>
    /// D334 item 7 by code: the files byte for byte what this graph builds now; every ❓ says why; every skip reason on the fixed list;
    /// every control fact outside tests (<c>ui-event</c> button, <c>form-field</c> other than a wrapper's insides, <c>menu-item</c>) is
    /// exactly one line, skipped line or set-aside line.
    /// </summary>
    public static JsonObject Check(string root, CodeGraph graph)
    {
        var set = Inventory.Build(graph, root);
        var problems = new List<string>();
        foreach (var (rel, text) in Render(set))
        {
            var path = Path.Combine(root, rel);
            if (!File.Exists(path)) problems.Add($"byte-for-byte: {rel} is missing (run `stangent inventory`)");
            else if (File.ReadAllText(path) != text) problems.Add($"byte-for-byte: {rel} isn't what this graph builds (run `stangent inventory`)");
        }
        var lines = set.AllLines.ToList();
        problems.AddRange(lines.Where(l => !l.Name.Visible && string.IsNullOrWhiteSpace(l.Name.Why)).Select(l => $"reasons: {l.At}: a ❓ that doesn't say why"));
        problems.AddRange(set.Skipped.Where(s => !Inventory.SkipReasons.Contains(s.Reason)).Select(s => $"skip list: {s.Line.At}: reason '{s.Reason}' isn't on D326's fixed list"));
        problems.AddRange(set.SetAside.Where(s => !Inventory.SetAsideReasons.Contains(s.Reason)).Select(s => $"set aside: {s.At}: reason '{s.Reason}' isn't a known one"));

        // Completeness: each control fact accounted for exactly once.
        var tests = graph.AllNodes.Where(n => n.IsTest).Select(n => n.Id).ToHashSet(StringComparer.Ordinal);
        var want = graph.AllFacts.Where(f => !tests.Contains(f.Owner) && (f.Kind == "ui-event" && Labels.IsButton(f) || f.Kind == "form-field" && f["inside"] != "wrapper" || f.Kind == "menu-item"))
            .Select(Key).GroupBy(k => k, StringComparer.Ordinal).ToDictionary(x => x.Key, x => x.Count(), StringComparer.Ordinal);
        var have = lines.Select(l => l.Fact).Concat(lines.SelectMany(l => l.Merged)).Concat(set.Skipped.SelectMany(s => s.Line.Merged.Prepend(s.Line.Fact))).Concat(set.SetAside.Select(s => s.Fact))
            .Select(Key).GroupBy(k => k, StringComparer.Ordinal).ToDictionary(x => x.Key, x => x.Count(), StringComparer.Ordinal);
        foreach (var (key, n) in want.OrderBy(x => x.Key, StringComparer.Ordinal))
        {
            var got = have.GetValueOrDefault(key);
            if (got != n) problems.Add($"complete: {key} is a control fact {n} time(s) but {got} line(s), skipped or set-aside entries");
        }
        problems.AddRange(have.Keys.Where(k => !want.ContainsKey(k)).Order(StringComparer.Ordinal).Select(k => $"complete: {k} is a line but no control fact"));
        return new JsonObject
        {
            ["ok"] = problems.Count == 0,
            ["counts"] = Counts(set),
            ["controls"] = want.Values.Sum(),
            ["problems"] = new JsonArray([.. problems.Order(StringComparer.Ordinal).Select(p => (JsonNode)p)]),
        };
    }

    static string Key(Fact f) => $"{f.Kind} {f.File}:{f.Line} {f.Owner} {string.Join(",", f.Data.OrderBy(d => d.Key, StringComparer.Ordinal).Select(d => $"{d.Key}={d.Value}"))}";
}
